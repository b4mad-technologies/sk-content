// pattern: role-driven-brain
import { encounters } from "./encounters.ts";
import {
	ALDWIN_ENTITY_KEY,
	COMPANION_ENTITY_KEYS,
	INNKEEPER_ENTITY_KEY,
} from "./lib/entity-keys.ts";
import { BUNDLE } from "./lib/ids.ts";
import { Q1_CELLAR_RAT_KEYS, Q1_CELLAR_SWARM_KEY, STORYLINE_NPC_KEYS } from "./quests.ts";

/** Derive hostile seats from the same placements that seed the adventure.
 * Friendly application profiles remain explicit; an ordinary actor does not
 * become hostile merely because it is absent from a manually maintained list. */
export function adventureCast() {
	const seats: { actor_key: string; profile: string; required: boolean }[] = [];
	const add = (actor_key: string, profile: string, required = false) =>
		seats.push({ actor_key, profile: `elven-mini/${profile}`, required });
	add(`${BUNDLE}/adventure/npc/crypt_warden_1`, "crypt-warden", true);
	add(ALDWIN_ENTITY_KEY, "aldwin", true);
	add(INNKEEPER_ENTITY_KEY, "mira", true);
	for (const key of [
		STORYLINE_NPC_KEYS.ysolde,
		STORYLINE_NPC_KEYS.tamsin,
		STORYLINE_NPC_KEYS.vessk,
	])
		add(key, "quest-giver");
	add(STORYLINE_NPC_KEYS.caddoc, "caddoc");
	add(STORYLINE_NPC_KEYS.jory, "jory");
	add(STORYLINE_NPC_KEYS.hesper, "hesper");
	add(COMPANION_ENTITY_KEYS.rogue, "rogue-companion");
	for (const key of [...Q1_CELLAR_RAT_KEYS, Q1_CELLAR_SWARM_KEY]) add(key, "role-driven");
	for (const call of encounters()) {
		if (call.toolName !== "spellkave_place_actor") continue;
		const p = call.params;
		if (typeof p.entity_key === "string") add(p.entity_key, "role-driven");
		else {
			if (typeof p.key_prefix !== "string" || typeof p.count !== "number")
				throw new Error(`Missing cast identity in ${call.label}`);
			for (let n = 1; n <= p.count; n++) add(`${BUNDLE}/${p.key_prefix}_${n}`, "role-driven");
		}
	}
	if (new Set(seats.map((seat) => seat.actor_key)).size !== seats.length)
		throw new Error("Duplicate adventure cast identity");
	return seats;
}

export function renderAdventureCast(): string {
	return (
		'# Generated by author/cast.ts via author/generate.ts. Do not hand-edit.\nschema_version = "1"\ncampaign_id = "elven-mini"\n' +
		adventureCast()
			.map(
				(seat) =>
					`\n[[actors]]\nactor_key = ${JSON.stringify(seat.actor_key)}\nprofile = ${JSON.stringify(seat.profile)}\ncredential_ref = "file:"\nrequired = ${seat.required}\n`,
			)
			.join("")
	);
}
