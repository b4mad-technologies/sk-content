import type { ChapterUnitSummary } from "../chapters/chapter-types";
import { AC_RESOURCE_ID } from "../chapters/playing-the-game/armor-class-units";
import { BUNDLE_ID } from "../chapters/playing-the-game/constants";
import { HP_ID } from "../chapters/playing-the-game/hp-units";
import { LEVEL_ID } from "../chapters/playing-the-game/level-units";
import { driveUnitScene, metadataCall, type VerbCall } from "../chapters/verb-runner";

const SELF_SUMMARY_ANCHOR = "playing-the-game.md § Damage and Healing > Hit Points";

/** ADR-0073 namespace this bundle registers for PLAYER self-summary bucket
 * membership (#2119) — audience `public`, one namespace per player surface. */
const SELF_SUMMARY_NAMESPACE = "ui.self_summary";

const HP_RESOURCE_ID = `${BUNDLE_ID}/${HP_ID}`;
const LEVEL_RESOURCE_ID = `${BUNDLE_ID}/${LEVEL_ID}`;

/**
 * Author-driven `ui.self_summary` membership for the three resources a
 * character sheet's compact vitals glance actually wants: HP, AC, level
 * (#2119). This replaces the old approach — the SDK's `readSelfSummary`
 * hardcoding a literal `"core"` resource tag it filtered states on, a magic
 * name no bundle was ever required to know (and this bundle deliberately
 * never authored — see `chapters/playing-the-game/fragments/identity.ts`'s
 * own "no consumer" note). ADR-0073's placement ladder rung 4 applies: which
 * states surface in a PLAYER-facing summary, and in what order, does not
 * change server behavior — it is metadata, not a tag the DSL gates on.
 *
 * Lives under `src/ui/`, not a chapter, and renders into its own fixture
 * root `fixtures/ui/` (not `base/<chapter>/`): surface membership is
 * editorial curation with no SRD source, its ordering is global across
 * chapters (not owned by any one book chapter), and later surfaces
 * (`ui.scene`, `ui.inventory`) will span chapters too (operator ruling,
 * #2119 follow-up).
 *
 * Deliberately NO quest attachments here: this bundle has no quest-tracking
 * states (generic SRD mechanics, not a scenario). An empty `quest` bucket in
 * `spellkave_self_summary` is the correct, honest result — not a gap.
 */
export async function buildSelfSummaryMetadataFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const calls: VerbCall[] = [
		metadataCall("self-summary-metadata", BUNDLE_ID, [
			{
				target: "namespace",
				key: SELF_SUMMARY_NAMESPACE,
				value: {
					audience: "public",
					description:
						"Player self-summary bucket membership: which resource_definition rows " +
						"surface in spellkave_self_summary's vitals/quest buckets, and in what order.",
				},
			},
			{
				target: { kind: "resource_definition", ref: HP_RESOURCE_ID },
				key: SELF_SUMMARY_NAMESPACE,
				value: { slot: "vitals", order: 10 },
			},
			{
				target: { kind: "resource_definition", ref: AC_RESOURCE_ID },
				key: SELF_SUMMARY_NAMESPACE,
				value: { slot: "vitals", order: 20 },
			},
			{
				target: { kind: "resource_definition", ref: LEVEL_RESOURCE_ID },
				key: SELF_SUMMARY_NAMESPACE,
				value: { slot: "vitals", order: 30 },
			},
		]),
	];
	const body = await driveUnitScene(BUNDLE_ID, calls);
	const header = [
		"# GENERATED by src/ui/self-summary.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# ADR-0073 metadata attachments (#2119): author-driven spellkave_self_summary",
		'# bucket membership. Replaces the old SDK-hardcoded "core"/"quest" resource',
		"# tag filter this bundle deliberately never authored (chapters/playing-the-game/",
		'# fragments/identity.ts\'s own "no consumer" note) — the SDK now reads THESE rows',
		"# instead of any literal tag. HP/AC/Level land in the `vitals` slot; this bundle",
		"# has no quest-tracking states, so it authors no `quest` attachments at all — the",
		"# resulting empty quest bucket is correct, not a gap.",
		"",
		`# anchor: ${SELF_SUMMARY_ANCHOR}`,
		"",
		"",
	].join("\n");
	return {
		toml: header + body,
		units: [
			{ kind: "metadata_namespaces", id: SELF_SUMMARY_NAMESPACE, sourcePk: "" },
			{
				kind: "metadata_attachments",
				id: `${SELF_SUMMARY_NAMESPACE}:${HP_RESOURCE_ID}`,
				sourcePk: "",
			},
			{
				kind: "metadata_attachments",
				id: `${SELF_SUMMARY_NAMESPACE}:${AC_RESOURCE_ID}`,
				sourcePk: "",
			},
			{
				kind: "metadata_attachments",
				id: `${SELF_SUMMARY_NAMESPACE}:${LEVEL_RESOURCE_ID}`,
				sourcePk: "",
			},
		],
	};
}
