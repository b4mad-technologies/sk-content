import type { ChapterUnitSummary } from "../chapters/chapter-types";
import { thrownConsumableUnits } from "../chapters/equipment/thrown-consumables";
import { BUNDLE_ID } from "../chapters/playing-the-game/constants";
import { SNEAK_ATTACK_ACTION_ID } from "../chapters/playing-the-game/sneak-attack-units";
import {
	OPPORTUNITY_ATTACK_ACTION_SUFFIX,
	UNARMED_STRIKE_DAMAGE_ACTION_SUFFIX,
} from "../chapters/playing-the-game/unarmed-strike-units";
import {
	MELEE_ATTACK_LOCAL_ID,
	RANGED_ATTACK_LOCAL_ID,
	SWING_ATTACK_LOCAL_ID,
} from "../chapters/playing-the-game/weapon-attack-units";
import { driveUnitScene, type VerbCall } from "../chapters/verb-runner";

/** ADR-0073 namespace this bundle registers for PLAYER affordance grouping
 * (T4c / sk-jay0.1.8.34.18) — audience `public`.
 *
 * Namespace ownership cannot switch by additive apply: the first bundle to
 * register a namespace string wins, and a later different-bundle registration
 * is rejected. There is no in-place namespace-ownership migration.
 * Disposable local only: `just wipe` then seed SRD, then adventure.
 * Hosted delivery uses the canonical API world load with the exact
 * artifact/reset handshake — never `just wipe` as a hosted procedure. */
export const AFFORDANCE_GROUP_NAMESPACE = "ui.affordance_group";

/** The only group this generator authors. Group-name knowledge stays here;
 * tools/readers stay generic over the payload string. */
export const AFFORDANCE_COMBAT_GROUP = "combat";

/** Mastery melee variants authored in `fragments/weapon-mastery-riders.ts`
 * as `${MELEE_ATTACK_LOCAL_ID}-<stem>` (`srd/attack/melee-sap`, …). */
const MASTERY_MELEE_VARIANT_STEMS = ["sap", "slow", "topple", "graze", "vex"] as const;

function attackActionAffordanceId(localId: string): string {
	return `${BUNDLE_ID}/${localId}/affordance`;
}

/**
 * Explicit generator-owned Attack-capability template identities.
 * Completeness is the authored `capability_id = srd/action/attack` set in
 * the seeded root bundle — not a path/name heuristic.
 */
export function attackCapabilityCombatTemplateIds(): string[] {
	return [
		attackActionAffordanceId(UNARMED_STRIKE_DAMAGE_ACTION_SUFFIX),
		attackActionAffordanceId(OPPORTUNITY_ATTACK_ACTION_SUFFIX),
		attackActionAffordanceId(MELEE_ATTACK_LOCAL_ID),
		attackActionAffordanceId(RANGED_ATTACK_LOCAL_ID),
		attackActionAffordanceId(SWING_ATTACK_LOCAL_ID),
		`${SNEAK_ATTACK_ACTION_ID}/affordance`,
		`${SNEAK_ATTACK_ACTION_ID}/affordance-ranged`,
		...MASTERY_MELEE_VARIANT_STEMS.map((stem) =>
			attackActionAffordanceId(`${MELEE_ATTACK_LOCAL_ID}-${stem}`),
		),
		...thrownConsumableUnits().map((unit) => `${unit.actionId}/affordance`),
	];
}

export async function buildAffordanceGroupsMetadataFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const templateIds = attackCapabilityCombatTemplateIds();
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "affordance-group-metadata-namespace",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_namespaces",
				rows: [
					{
						namespace: AFFORDANCE_GROUP_NAMESPACE,
						audience: "public",
						bundle_id: BUNDLE_ID,
						description:
							"UI-facing affordance grouping (e.g. 'combat'): which affordance_template " +
							"rows a player/agent tool surface groups together under a named filter.",
					},
				],
			},
		},
		{
			toolName: "spellkave_write_rows",
			label: "affordance-group-attack-capability-combat",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_attachments",
				rows: templateIds.map((target_ref) => ({
					target_kind: "affordance_template",
					target_ref,
					namespace: AFFORDANCE_GROUP_NAMESPACE,
					payload_json: JSON.stringify({ group: AFFORDANCE_COMBAT_GROUP }),
					bundle_id: BUNDLE_ID,
					source: "manifest",
				})),
			},
		},
	];
	const body = await driveUnitScene(BUNDLE_ID, calls);
	const header = [
		"# GENERATED by src/ui/affordance-groups.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# ADR-0073 metadata attachments (T4c / sk-jay0.1.8.34.18): author-driven",
		"# spellkave_affordance_* group membership. SRD owns SRD template memberships",
		"# for every production affordance_template whose capability_id is",
		'# srd/action/attack. Payload contract: {"group":"combat"}.',
		"# Namespace ownership cannot switch by additive apply. Disposable local: just wipe then seed. Hosted: canonical API world load / reset handshake — never just wipe.",
		"",
		"",
	].join("\n");
	return {
		toml: header + body,
		units: [
			{ kind: "metadata_namespaces", id: AFFORDANCE_GROUP_NAMESPACE, sourcePk: "" },
			...templateIds.map((id) => ({
				kind: "metadata_attachments",
				id: `${AFFORDANCE_GROUP_NAMESPACE}:${id}`,
				sourcePk: "",
			})),
		],
	};
}
