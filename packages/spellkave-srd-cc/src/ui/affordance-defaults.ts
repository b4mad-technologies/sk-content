import type { ChapterUnitSummary } from "../chapters/chapter-types";
import { BUNDLE_ID } from "../chapters/playing-the-game/constants";
import { DODGE_ACTION_ID } from "../chapters/playing-the-game/fragments/dodge";
import { driveUnitScene, type VerbCall } from "../chapters/verb-runner";

/** Public draft suggestions. They never change reducer admission. */
export const AFFORDANCE_DEFAULTS_NAMESPACE = "ui.affordance_defaults";

const DEFAULTS = [
	{
		templateId: `${DODGE_ACTION_ID}/affordance`,
		payload: { version: 1, target: { kind: "actor" } },
	},
] as const;

export async function buildAffordanceDefaultsMetadataFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "affordance-defaults-metadata-namespace",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_namespaces",
				rows: [
					{
						namespace: AFFORDANCE_DEFAULTS_NAMESPACE,
						audience: "public",
						bundle_id: BUNDLE_ID,
						description:
							"Public author-published shell draft values. Presentation only; never eligibility or reducer fallback.",
					},
				],
			},
		},
		{
			toolName: "spellkave_write_rows",
			label: "affordance-defaults-examples",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_attachments",
				rows: DEFAULTS.map(({ templateId, payload }) => ({
					target_kind: "affordance_template",
					target_ref: templateId,
					namespace: AFFORDANCE_DEFAULTS_NAMESPACE,
					payload_json: JSON.stringify(payload),
					bundle_id: BUNDLE_ID,
					source: "manifest",
				})),
			},
		},
	];
	const body = await driveUnitScene(BUNDLE_ID, calls);
	return {
		toml: `# GENERATED by src/ui/affordance-defaults.ts — DO NOT EDIT BY HAND.\n# Public presentation metadata; see packages/spellkave-world-author/docs/patterns/advisory-action-default.md.\n\n${body}`,
		units: [
			{ kind: "metadata_namespaces", id: AFFORDANCE_DEFAULTS_NAMESPACE, sourcePk: "" },
			...DEFAULTS.map(({ templateId }) => ({
				kind: "metadata_attachments",
				id: `${AFFORDANCE_DEFAULTS_NAMESPACE}:${templateId}`,
				sourcePk: "",
			})),
		],
	};
}
