import type { ChapterUnitSummary } from "../chapters/chapter-types";
import { BUNDLE_ID } from "../chapters/playing-the-game/constants";
import { STEP_AFFORDANCE_ID } from "../chapters/playing-the-game/fragments/grid";
import { SPEAK_TO_AFFORDANCE_ID } from "../chapters/playing-the-game/fragments/speech";
import { driveUnitScene, type VerbCall } from "../chapters/verb-runner";

// pattern: advisory-action-cue
/** Public, presentation-only action ranking/explanation metadata. */
export const AFFORDANCE_CUE_NAMESPACE = "ui.affordance_cue";

const CUES = [
	{
		templateId: SPEAK_TO_AFFORDANCE_ID,
		payload: { rank: 4, hint: "Speak directly to a visible person." },
	},
	{
		templateId: STEP_AFFORDANCE_ID,
		payload: { rank: 2, hint: "A visible exit can take you onward." },
	},
] as const;

export async function buildAffordanceCuesMetadataFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "affordance-cue-metadata-namespace",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_namespaces",
				rows: [
					{
						namespace: AFFORDANCE_CUE_NAMESPACE,
						audience: "public",
						bundle_id: BUNDLE_ID,
						description:
							"Public action ranking and explanation hints. Presentation only; never action eligibility or a bound target.",
					},
				],
			},
		},
		{
			toolName: "spellkave_write_rows",
			label: "affordance-cue-examples",
			params: {
				bundle: BUNDLE_ID,
				kind: "metadata_attachments",
				rows: CUES.map(({ templateId, payload }) => ({
					target_kind: "affordance_template",
					target_ref: templateId,
					namespace: AFFORDANCE_CUE_NAMESPACE,
					payload_json: JSON.stringify(payload),
					bundle_id: BUNDLE_ID,
					source: "manifest",
				})),
			},
		},
	];
	const body = await driveUnitScene(BUNDLE_ID, calls);
	return {
		toml:
			"# GENERATED by src/ui/affordance-cues.ts — DO NOT EDIT BY HAND.\n" +
			"# Public presentation metadata; see ledger/designs/advisory-interaction-cues.md.\n\n" +
			body,
		units: [
			{ kind: "metadata_namespaces", id: AFFORDANCE_CUE_NAMESPACE, sourcePk: "" },
			...CUES.map(({ templateId }) => ({
				kind: "metadata_attachments",
				id: `${AFFORDANCE_CUE_NAMESPACE}:${templateId}`,
				sourcePk: "",
			})),
		],
	};
}
