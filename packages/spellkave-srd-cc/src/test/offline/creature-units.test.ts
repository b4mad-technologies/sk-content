describe("creature-tag-values.ts", () => {
	it("normalizes both '0' and '0.000' to the same slug (the design doc's own §3 inconsistency)", () => {
		expect(normalizeChallengeRating("0")).toBe("0");
		expect(normalizeChallengeRating("0.000")).toBe("0");
	});

	it("normalizes fractional CRs to slash-slugs, whole CRs to bare integers", () => {
		expect(normalizeChallengeRating("0.125")).toBe("1-8");
		expect(normalizeChallengeRating("0.250")).toBe("1-4");
		expect(normalizeChallengeRating("0.500")).toBe("1-2");
		expect(normalizeChallengeRating("10.000")).toBe("10");
		expect(normalizeChallengeRating("30.000")).toBe("30");
	});

	it("throws loudly on an unrecognized raw CR string", () => {
		expect(() => normalizeChallengeRating("2.500")).toThrow();
	});

	it("ships exactly 5 sourced Size values + 1 class row (no Tiny in this dataset)", () => {
		const units = buildSizeTagValueUnits();
		expect(units).toHaveLength(6);
		expect(units.map((unit) => unit.tag)).toContain("srd.size");
		for (const slug of ["small", "medium", "large", "huge", "gargantuan"]) {
			expect(units.map((unit) => unit.tag)).toContain(`srd.size.${slug}`);
		}
	});

	it("derives the CR catalog mechanically from the cache (never hand-typed)", () => {
		const units = buildCrTagValueUnits();
		const rawValues = new Set(readCreatures().map((creature) => creature.challengeRating));
		const expectedSlugCount = new Set([...rawValues].map((raw) => normalizeChallengeRating(raw)))
			.size;
		expect(units).toHaveLength(expectedSlugCount + 1); // +1 class row
		expect(units.map((unit) => unit.tag)).toContain("srd.cr");
		expect(units.map((unit) => unit.tag)).toContain("srd.cr.1-4");
		expect(units.map((unit) => unit.tag)).toContain("srd.cr.0");
	});
});

describe("creature-units.ts", () => {
	it("builds exactly 331 identity units with unique entity ids", () => {
		const units = buildCreatureUnits();
		expect(units).toHaveLength(331);
		expect(new Set(units.map((unit) => unit.entityId)).size).toBe(331);
		expect(units.filter((unit) => unit.tags.includes(VOCAL_COMMUNICATION_TAG))).toHaveLength(179);
		for (const slug of ["zombie", "kraken", "shield-guardian"]) {
			const unit = units.find((candidate) => candidate.slug === slug);
			expect(unit, slug).toBeDefined();
			expect(
				creatureHasVocalCommunication(unit?.record as NonNullable<typeof unit>["record"]),
			).toBe(false);
			expect(unit?.tags).not.toContain(VOCAL_COMMUNICATION_TAG);
		}
		for (const slug of ["aboleth", "giant-eagle", "werewolf"]) {
			const unit = units.find((candidate) => candidate.slug === slug);
			expect(unit, slug).toBeDefined();
			expect(unit?.tags).toContain(VOCAL_COMMUNICATION_TAG);
		}
	});

	it("carries no alignment tag for Unaligned Creatures (Wolf)", () => {
		const wolf = buildCreatureUnits().find((unit) => unit.slug === "wolf");
		expect(wolf).toBeDefined();
		expect(wolf?.tags.some((tag) => tag.startsWith("srd.alignment."))).toBe(false);
	});

	it("carries a valid srd.alignment.<slug> tag for an aligned creature (Goblin Warrior)", () => {
		const goblin = buildCreatureUnits().find((unit) => unit.slug === "goblin-warrior");
		expect(goblin?.tags).toContain("srd.alignment.chaotic-neutral");
	});

	it("clamps the one out-of-bounds ability score in this dataset (Octopus CHA -3 -> 0)", () => {
		const octopus = buildCreatureUnits().find((unit) => unit.slug === "octopus");
		expect(octopus).toBeDefined();
		const cha = octopus?.initialStates.find((state) => state.state === "srd/cha");
		expect(cha?.valueInt).toBe(0);
		const rawCha = rawCreatureField("srd-2024_octopus", "ability_score_charisma");
		expect(rawCha).toBe(-3); // pin the raw anomaly so a future cache fix is caught here
	});

	it("converts walk feet to speed-walk cells (30 ft -> 6 cells, Goblin Warrior)", () => {
		const goblin = buildCreatureUnits().find((unit) => unit.slug === "goblin-warrior");
		const speedWalk = goblin?.initialStates.find((state) => state.state === "srd/speed-walk");
		expect(speedWalk?.valueInt).toBe(6);
	});

	it("seeds srd/xp_value from the CR table (Goblin Warrior CR 1/4 = 50; Commoner CR 0 = 0)", () => {
		const units = buildCreatureUnits();
		const goblin = units.find((unit) => unit.slug === "goblin-warrior");
		const commoner = units.find((unit) => unit.slug === "commoner");
		expect(goblin?.initialStates.find((state) => state.state === "srd/xp_value")?.valueInt).toBe(
			50,
		);
		expect(commoner?.initialStates.find((state) => state.state === "srd/xp_value")?.valueInt).toBe(
			0,
		);
		expect(xpValueForCreature(goblin?.record as NonNullable<typeof goblin>["record"])).toBe(50);
	});

	it("honors Octopus's authored 10 XP exception on CR 0", () => {
		const octopus = buildCreatureUnits().find((unit) => unit.slug === "octopus");
		expect(octopus?.record.experiencePointsInteger).toBe(10);
		expect(octopus?.initialStates.find((state) => state.state === "srd/xp_value")?.valueInt).toBe(
			10,
		);
		const raw = rawCreatureField("srd-2024_octopus", "experience_points_integer");
		expect(raw).toBe(10);
	});

	it("seeds Adult Black Dragon fly/swim cells and language tags from the cache", () => {
		const dragon = buildCreatureUnits().find((unit) => unit.slug === "adult-black-dragon");
		expect(dragon).toBeDefined();
		expect(dragon?.initialStates.find((state) => state.state === "srd/speed-fly")?.valueInt).toBe(
			16,
		);
		expect(dragon?.initialStates.find((state) => state.state === "srd/speed-swim")?.valueInt).toBe(
			8,
		);
		expect(dragon?.tags).toEqual(
			expect.arrayContaining(["srd.language.common", "srd.language.draconic"]),
		);
	});

	it("equips Adult Black Dragon Rend as a natural weapon (CR 17, outside the CR 0–4 plan)", () => {
		const seed = buildEquipmentSeeds().find((row) => row.slug === "adult-black-dragon");
		expect(seed?.naturalWeaponSlug).toBe("adult-black-dragon-rend");
		expect(seed?.equippedAttack.displayName).toBe("Rend");
	});
});

