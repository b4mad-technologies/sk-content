function rawCreatureField(pk: string, field: string): unknown {
	const raw = JSON.parse(readFileSync(path.join(CACHE_OPEN5E_DIR, "Creature.json"), "utf8")) as {
		pk: string;
		fields: Record<string, unknown>;
	}[];
	const record = raw.find((row) => row.pk === pk);
	if (record === undefined) throw new Error(`test setup: no Creature.json record with pk '${pk}'.`);
	return record.fields[field];
}

