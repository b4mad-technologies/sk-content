describe("starter-behaviors.ts", () => {
	it("giantRatBiteFallback pins the same numbers the sourced desc prose states (+5 to-hit, 1d4+3 Piercing)", () => {
		const action = creatureActionsByParent("srd-2024_giant-rat").find((row) => row.name === "Bite");
		expect(action?.desc).toBe("Melee Attack Roll: +5, reach 5 feet. 5 (1d4 + 3) Piercing damage.");
	});

	// L7 bestiary CR 0–4: baked-ordinal actions cover every multiattack (and
	// flat-damage / ability-mismatch single) in the band — not only the two
	// bears. The original 8 starters keep their routes (bears still baked).
	it("builds baked-ordinal actions for every CR 0–4 multiattack/baked single (includes both bears)", () => {
		const result = buildStarterBehaviors();
		expect(result.actionIds.length).toBeGreaterThan(2);
		expect(result.actionIds).toContain("srd/creature/black-bear/action/multiattack");
		expect(result.actionIds).toContain("srd/creature/brown-bear/action/multiattack");
		expect(result.creatureSlugs).toContain("black-bear");
		expect(result.creatureSlugs).toContain("brown-bear");
		expect(result.actionIds.length).toBeGreaterThanOrEqual(result.creatureSlugs.length);
	});

	// The retirement's own load-bearing claim, asserted rather than trusted:
	// the shared `srd/attack/ranged` archetype (DEX mod + the baked
	// `srd/proficiency_bonus`, then the equipped item's own damage slot)
	// reproduces all THREE retired ranged
	// statblock lines EXACTLY, from facts `creature-units.ts` already seeds.
	// If a cache resync moves any of these creatures' DEX or CR, this fails
	// and the retirement has to be re-derived — it does not silently start
	// under-hitting.
	//
	// Each creature's definition equips the weapon named by its source row.
	it("the shared ranged archetype reproduces the retired Goblin Warrior / Skeleton / Bandit numbers exactly", () => {
		const units = buildCreatureUnits();
		for (const [slug, actionPk, dieSides] of [
			["goblin-warrior", "srd-2024_goblin-warrior_shortbow", 6],
			["skeleton", "srd-2024_skeleton_shortbow", 6],
			["bandit", "srd-2024_bandit_light-crossbow", 8],
		] as const) {
			const unit = units.find((candidate) => candidate.slug === slug);
			expect(unit, slug).toBeDefined();
			const stat = (id: string): number => {
				const row = unit?.initialStates.find((state) => state.state === `srd/${id}`);
				expect(row, `${slug}/${id}`).toBeDefined();
				return row?.valueInt ?? Number.NaN;
			};
			// Floor division matches the archetype's own modifier expression.
			const dexMod = Math.floor((stat("dex") - 10) / 2);
			const attack = creatureActionAttackByParent(actionPk);
			expect(attack, actionPk).toBeDefined();
			expect(dexMod + stat("proficiency_bonus"), `${slug} to-hit`).toBe(attack?.toHitMod);
			expect(attack?.damageDieCount, `${slug} die count`).toBe(1);
			expect(attack?.damageDieType?.replace(/^D/i, ""), `${slug} die`).toBe(String(dieSides));
			expect(dexMod, `${slug} damage bonus`).toBe(attack?.damageBonus);
		}
	});

	// The Bandit's 1d8 comes from the equipped Light Crossbow's own srd/damage
	// slot (equipment/weapon-damage-source-units.ts,
	// weapon-damage-source retirement 2026-08-13). Pin that the die the
	// equipment module ships really is the 1d8 piercing the stat block above
	// demands, so the two halves of route 2 cannot drift apart silently.
	it("the Light Crossbow's own die is the 1d8 piercing the Bandit's retirement depends on", () => {
		const attack = creatureActionAttackByParent("srd-2024_bandit_light-crossbow");
		expect(attack?.damageDieType?.replace(/^D/i, "")).toBe("8");
		expect(attack?.extraDamageType ?? attack?.damageType).toBe("piercing");
	});

	// BL-49's own load-bearing claim, asserted rather than trusted. The Giant
	// Rat is the creature that PROVES the finesse branch: both its numbers
	// are Dexterity-driven, so a Strength-only to-hit could not reproduce
	// them and it was stuck bespoke. Numbers come from the SAME parser the
	// module uses (giantRatBiteFallback), never re-typed here.
	it("the shared melee archetype reproduces the retired Giant Rat Bite exactly, and ONLY via the finesse branch", () => {
		const sourced = giantRatBiteFallback();
		const unit = buildCreatureUnits().find((candidate) => candidate.slug === "giant-rat");
		expect(unit, "giant-rat").toBeDefined();
		const stat = (id: string): number => {
			const row = unit?.initialStates.find((state) => state.state === `srd/${id}`);
			expect(row, `giant-rat/${id}`).toBeDefined();
			return row?.valueInt ?? Number.NaN;
		};
		const strMod = expectedAbilityModifier(stat("str"));
		const dexMod = expectedAbilityModifier(stat("dex"));
		// The finesse branch selects the higher of the two.
		const finesseMod = Math.max(strMod, dexMod);
		expect(finesseMod + stat("proficiency_bonus"), "giant-rat to-hit").toBe(sourced.toHitMod);
		expect(finesseMod, "giant-rat damage bonus").toBe(sourced.damageBonus);
		// The wielded item's own srd/damage slot supplies the die.
		expect(sourced.diceExpr).toBe("1d4");
		expect(sourced.damageType).toBe("piercing");
		// WITHOUT finesse the archetype could NOT reproduce these numbers —
		// this is why the Giant Rat was the blocked case, and it guards
		// against the tag silently coming off the natural weapon.
		expect(strMod).toBeLessThan(dexMod);
		expect(strMod + stat("proficiency_bonus")).not.toBe(sourced.toHitMod);
	});

	it("starterBehaviorUnitSummaries yields one action_definitions row per baked-ordinal action", () => {
		const result = buildStarterBehaviors();
		const summaries = starterBehaviorUnitSummaries(result);
		expect(summaries).toHaveLength(result.actionIds.length);
		expect(summaries.every((summary) => summary.kind === "action_definitions")).toBe(true);
	});
});

/**
 * Per-entity fixture layout (operator directive 2026-08-06): a fresh
 * `generateMonsters()` render now costs ~113s in-process (331 separate
 * per-creature validated workspaces, was ~10 chunked ones, ~15-20s) — long
 * enough to trip vitest's own worker↔main RPC heartbeat (birpc's fixed ~60s
 * ceiling, no `vitest.config` knob exists for it; `pipeline.test.ts`'s own
 * module header has the full research). That heartbeat mechanism is
 * SEPARATE from any test's own declared `it()`/`beforeAll` timeout — raising
 * this describe block's own timeout stopped it failing on its OWN clock, but
 * the RPC heartbeat still threw its own "Unhandled Error" and failed the
 * WHOLE suite run regardless (team decision, 2026-08-06).
 *
 * FIX: assert against the COMMITTED `fixtures/base/monsters/` tree instead
 * of a second in-process render, never against `pipeline.test.ts`'s own
 * child-process result (that would couple two test files' execution order —
 * vitest runs files in separate workers, so this file can't safely depend on
 * `pipeline.test.ts` having already written its own artifact). This is
 * SOUND, not a weaker proof: `pipeline.test.ts`'s own "is deterministic: two
 * in-memory runs produce byte-identical output" test ALREADY proves clean-
 * regen byte-identity (a fresh render === the committed bytes) for the
 * fully-assembled bundle, monsters included — any drift between the
 * generator and the committed tree is caught THERE, not silently missed
 * here. Reading the committed files costs milliseconds and carries zero
 * heartbeat exposure.
 */
describe("generateMonsters (committed fixtures — no second in-process render, module header)", () => {
	it("throws loudly when called without a target (srd/str..srd/hp would not resolve)", async () => {
		await expect(generateMonsters()).rejects.toThrow(/committed bundle target/);
	});

	it("the committed fixtures carry exactly 331 per-creature identity files", () => {
		const monstersDir = new URL("../../../fixtures/base/monsters/", import.meta.url);
		const tomlFiles = readdirSync(monstersDir).filter((name) => name.endsWith(".toml"));
		// tag-values.toml + starter-behaviors.toml are shared axis-level files
		// (module header's own carve-out), never per-creature. monsters.toml,
		// monsters-a-z.toml, and animals.toml are the chapter's reader
		// metadata (compendium-metadata.ts), colocated here since they
		// document this chapter, also never per-creature. `catalogue.toml`
		// no longer exists in this directory at all (sk-jay0.3.5.59: the
		// monsters catalogue listing carries no authored payload, so the
		// website derives it directly instead of srd-cc emitting a file) —
		// kept in this exclusion set is harmless (a name absent from
		// `tomlFiles` filters out as a no-op) but listed here for the
		// filter's own historical completeness, not because the file exists.
		const NON_CREATURE_FILES = new Set([
			"tag-values.toml",
			"starter-behaviors.toml",
			"catalogue.toml",
			"monsters.toml",
			"monsters-a-z.toml",
			"animals.toml",
		]);
		const creatureFiles = tomlFiles.filter((name) => !NON_CREATURE_FILES.has(name));
		expect(creatureFiles).toHaveLength(331);
	});

	it("Aboleth's own committed fixture carries its entity_definitions row with the expected shape", () => {
		const content = readFileSync(
			new URL("../../../fixtures/base/monsters/aboleth.toml", import.meta.url),
			"utf8",
		);
		expect(content).toContain('entity_def_id = "srd/creature/aboleth"');
		expect(content).toContain('state_id = "srd/ac"');
		expect(content).toContain('state_id = "srd/xp_value"');
	});
});
