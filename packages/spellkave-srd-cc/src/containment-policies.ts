// pattern: container-with-loot
import type { AuthorTarget } from "@spellkave/tool-authoring";
import { driveUnitScene, type VerbCall } from "./chapters/verb-runner";

type Row = Record<string, unknown>;
type Manifest = Record<string, unknown>;

export const OPEN_CONTENTS_POLICY = "srd/containment/open";
export const CORPSE_CONTENTS_POLICY = "srd/containment/corpse";
export const CONTAINMENT_POLICIES_PATH = "base/playing-the-game/containment-policies.toml";

const rows = (manifest: Manifest, kind: string): Row[] =>
	(manifest[kind] as Row[] | undefined) ?? [];

/** Select from this render's authored facts, including runtime initial-containment seeds. */
export function containmentPolicyBindings(manifest: Manifest): Row[] {
	const bodies = new Set<string>();
	const containers = new Set<string>();
	for (const row of rows(manifest, "entity_definition_tag")) {
		if (row.tag === "srd.creature") bodies.add(String(row.entity_def_id));
		if (row.tag === "srd.item.container") containers.add(String(row.entity_def_id));
	}
	for (const row of rows(manifest, "entity_definition_initial_containment")) {
		containers.add(String(row.entity_def_id));
	}
	const entities = new Map(rows(manifest, "entities").map((r) => [r.entity_key, r.entity_def_id]));
	for (const row of rows(manifest, "entity_containment")) {
		const definition = entities.get(row.container_entity_key);
		if (definition !== undefined) containers.add(String(definition));
	}
	return [...new Set([...bodies, ...containers])].sort().map((entity_def_id) => ({
		bundle_id: "srd",
		entity_def_id,
		policy_id: bodies.has(entity_def_id) ? CORPSE_CONTENTS_POLICY : OPEN_CONTENTS_POLICY,
	}));
}

/** Reuse existing dead state; unconscious or merely unbound living bodies stay private. */
export async function buildContainmentPoliciesFragment(
	manifest: Manifest,
	target: AuthorTarget,
): Promise<string> {
	const write = (kind: string, rows: Row[]): VerbCall => ({
		toolName: "spellkave_write_rows",
		label: `containment:${kind}`,
		params: { bundle: "srd", kind, rows },
	});
	const body = await driveUnitScene(
		"srd",
		[
			write("containment_policy_definition", [
				{
					bundle_id: "srd",
					policy_id: OPEN_CONTENTS_POLICY,
					exposure_predicate_source: "true == true",
					access_predicate_source: "true == true",
				},
				{
					bundle_id: "srd",
					policy_id: CORPSE_CONTENTS_POLICY,
					exposure_predicate_source: "target.status('srd/condition/dead') == true",
					access_predicate_source: "target.status('srd/condition/dead') == true",
				},
			]),
			write("entity_definition_containment_policy", containmentPolicyBindings(manifest)),
		],
		target,
	);
	return (
		"# GENERATED by src/containment-policies.ts — DO NOT EDIT BY HAND.\n" +
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate\n" +
		"# pattern: container-with-loot\n\n" +
		body
	);
}
