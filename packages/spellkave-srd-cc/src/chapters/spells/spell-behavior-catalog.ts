export function spellBehaviorPlansByShape(shape: SpellBehaviorShape): SpellBehaviorPlan[] {
	return SPELL_BEHAVIOR_PLANS.filter((plan) => plan.shape === shape);
}

export function spellBehaviorPlanBySlug(slug: string): SpellBehaviorPlan | undefined {
	return SPELL_BEHAVIOR_PLANS.find((plan) => plan.slug === slug);
}

export function isExpressibleShape(shape: SpellBehaviorShape): boolean {
	return !shape.startsWith("na_");
}

export const EXPRESSIBLE_SPELL_PLANS: readonly SpellBehaviorPlan[] = SPELL_BEHAVIOR_PLANS.filter(
	(plan) => isExpressibleShape(plan.shape),
);
