export type SaveAbility =
	| "dexterity"
	| "wisdom"
	| "constitution"
	| "strength"
	| "intelligence"
	| "charisma";

export type AoeShape =
	| { kind: "cone"; rangeFeet: number; halfAngleDeg: number }
	| { kind: "sphere"; radiusFeet: number }
	| { kind: "cube"; extentFeet: number };

export interface MultiInstanceSpec {
	dice: string;
	type: string;
	toHit?: boolean;
}

export interface SpellBehaviorPlan {
	slug: string;
	name: string;
	level: 0 | 1 | 2;
	sourcePk: string;
	shape: SpellBehaviorShape;
	naReason?: string;
	dice?: string;
	damageType?: string;
	melee?: boolean;
	rangeFeet?: number;
	cost?: 1 | 2;
	saveAbility?: SaveAbility;
	half?: boolean;
	aoe?: AoeShape;
	center?: "self" | "target";
	instances?: readonly MultiInstanceSpec[];
	autoHit?: boolean;
	acBonus?: number;
	concentration?: boolean;
	partial?: string;
	/** Condition definition local id stem under bundle (e.g. condition/spell/blessed). */
	conditionLocalId?: string;
	/** Existing catalog condition id to ApplyStatus (e.g. srd/condition/charmed). */
	conditionId?: string;
	/**
	 * End the condition at the caster's long rest. A compromise for spells with a
	 * minutes-long duration: ApplyStatus has no first-cast tick expiry, and the real
	 * duration needs Rust (sk-jay0.1.55.40).
	 */
	endsAtCasterLongRest?: boolean;
	/** Roll-mod magnitude expression (e.g. "1d4" or "-1d4"). */
	rollModExpr?: string;
	/** Resolution scopes the roll-mod applies to. */
	rollModScopes?: readonly ("attack_roll" | "ability_check" | "dex_save")[];
	/** Temp HP dice or fixed grant expression. */
	tempHpExpr?: string;
	/** Lingering zone pulse dice. */
	zoneDice?: string;
	/** Zone pulse damage type. */
	zoneDamageType?: string;
	/** Zone radius feet (sphere). */
	zoneRadiusFeet?: number;
	/** Zone pulse repeats (default 10). */
	zoneRepeats?: number;
	/** Env-state id local stem for fog/darkness markers. */
	envStateLocalId?: string;
	/** Summon blueprint entity_def_id. */
	summonEntityDef?: string;
	/** When true, emit slot-2 upcast sibling action from SpellCastingOption. */
	upcast?: boolean;
	/** speed_buff: cells added to srd/speed-walk (5 ft per cell). */
	speedBonusCells?: number;
	/** object_flag: payload flag name (e.g. locked). */
	objectFlag?: string;
	/** object_flag: bool value written. */
	objectFlagValue?: boolean;
	/** trace_cast: trace kind local id stem. */
	traceKindLocalId?: string;
	/** mark/condition/speed self-only cast. */
	selfOnly?: boolean;
	/** condition_roll_mod: use Advantage delta_kind instead of Plus. */
	rollAdvantage?: boolean;
}

