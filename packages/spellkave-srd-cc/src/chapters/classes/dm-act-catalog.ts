// pattern: identity-tag-capability-grant
// DOC-IMPL: scripted-dm-acts#class-progression-and-selected-training
// ADR-0155 D-3: executable grants are generated from the assembled SRD
// metadata and the same catalogues the creation wizard reads.
import { buildCreationClassCatalog } from "@spellkave/adventure-runtime/dm/creation";
import {
	advancementChoicesForClassLevel,
	grantableAdvancementCapabilities,
} from "@spellkave/adventure-runtime/dm/data";
import {
	SRD_BACKGROUND_CATALOG,
	SRD_CLASS_CATALOG,
} from "@spellkave/adventure-runtime/dm/data/srd-catalog";
import type { AuthorTarget } from "@spellkave/tool-authoring";
import { driveUnitScene, type VerbCall } from "../verb-runner";

export interface DmGrantCatalogue {
	tags: { tag: string; prefix: string; bundle_id: string; description: string }[];
	grants: { tag: string; capability_id: string; bundle_id: string }[];
	pickable: Record<string, string[]>;
}
export function dmGrantCatalog(target: AuthorTarget): DmGrantCatalogue {
	const groups: Record<string, Set<string>> = Object.fromEntries(
		["skill", "cantrip", "prepared-spell", "origin-feat", "choice-member", "proficiency"].map(
			(kind) => [kind, new Set<string>()],
		),
	);
	const tags: DmGrantCatalogue["tags"] = [];
	const grants: DmGrantCatalogue["grants"] = [];
	const add = (kind: string, ids: readonly string[]) => {
		for (const id of ids)
			if (target.resolveRef("capability_definitions", id)) groups[kind]?.add(id);
	};
	for (const cls of SRD_CLASS_CATALOG) {
		const catalogue = buildCreationClassCatalog(target, cls.slug);
		add("skill", catalogue.skills.skillCapabilityIds);
		add(
			"cantrip",
			catalogue.cantripOptions.map((option) => option.capabilityId),
		);
		add(
			"prepared-spell",
			catalogue.preparedOptions.map((option) => option.capabilityId),
		);
		add(
			"proficiency",
			(catalogue.equipmentChoices ?? []).flatMap((menu) =>
				menu.options.flatMap((option) =>
					option.proficiencyCapabilityId === undefined ? [] : [option.proficiencyCapabilityId],
				),
			),
		);
		for (let level = 1; level <= 20; level++) {
			const tag = `srd.advancement.${cls.slug}.${level}`;
			tags.push({
				tag,
				prefix: "srd.advancement",
				bundle_id: "srd",
				description: `${cls.displayName} level ${level}: backed srd.advancement_grant capabilities. Unsupported grants remain in the advancement gap report.`,
			});
			for (const capability_id of grantableAdvancementCapabilities(target, cls.slug, level)
				.grantable)
				grants.push({ tag, capability_id, bundle_id: "srd" });
			for (const choice of advancementChoicesForClassLevel(target, cls.slug, level))
				add("choice-member", choice.memberCapabilityIds);
		}
	}
	for (const background of SRD_BACKGROUND_CATALOG) {
		add("skill", background.skillCapabilityIds);
		if (background.featEntityId !== null) add("origin-feat", [background.featEntityId]);
	}
	const pickable = Object.fromEntries(
		Object.entries(groups).map(([kind, ids]) => [kind, [...ids].sort()]),
	);
	for (const capability_id of [...new Set(Object.values(pickable).flat())].sort()) {
		const tag = `srd.feature.${capability_id.replaceAll("/", ".")}`;
		tags.push({
			tag,
			prefix: "srd.feature",
			bundle_id: "srd",
			description: `Chosen capability: ${capability_id}.`,
		});
		grants.push({ tag, capability_id, bundle_id: "srd" });
	}
	// Features the advancement metadata does not reach. Champion is the only SRD
	// fighter subclass, so its level 3 feature rides the fighter level tag.
	for (const [tag, capability_id] of [
		["srd.advancement.rogue.1", "srd/class-feature/rogue/sneak-attack"],
		["srd.advancement.fighter.3", "srd/class-feature/fighter/champion/improved-critical"],
	] as const) {
		if (!grants.some((row) => row.tag === tag && row.capability_id === capability_id))
			grants.push({ tag, capability_id, bundle_id: "srd" });
	}
	return { tags, grants, pickable };
}

export async function buildDmGrantFragment(target: AuthorTarget): Promise<string> {
	const catalogue = dmGrantCatalog(target);
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "dm-grant-tags",
			params: { bundle: "srd", kind: "tag_value_definitions", rows: catalogue.tags },
		},
		{
			toolName: "spellkave_write_rows",
			label: "dm-tag-grants",
			params: { bundle: "srd", kind: "tag_capability_grant", rows: catalogue.grants },
		},
	];
	return (
		"# GENERATED by src/chapters/classes/dm-act-catalog.ts — DO NOT EDIT.\n# pattern: identity-tag-capability-grant\n" +
		(await driveUnitScene("srd", calls, target, {
			onlyTagValueDefinitionTags: catalogue.tags.map((row) => row.tag),
		}))
	);
}
