/** Service.json purchase rows. Not items. Cost is copper; the period stays text. */
import { readFileSync } from "node:fs";
import path from "node:path";
import type { AuthorTarget } from "@spellkave/tool-authoring";
import { CACHE_OPEN5E_DIR } from "../../open5e/paths.ts";
import type { ChapterUnitSummary } from "../chapter-types.ts";
import { driveUnitScene } from "../verb-runner.ts";
import { costCpFromGpString, itemMeasureResourceCalls } from "./item-measures.ts";

const STABLING_PK = "srd-2024_stabling-per-day";

interface ServiceRow {
	pk: string;
	name: string;
	desc: string;
	cost: string;
	detail: string | null;
}

export interface ServiceUnit {
	pk: string;
	slug: string;
	name: string;
	description: string;
	costCp: number;
	detail: string;
	entityId: string;
}

function readServices(): ServiceRow[] {
	const raw: unknown = JSON.parse(
		readFileSync(path.join(CACHE_OPEN5E_DIR, "Service.json"), "utf8"),
	);
	if (!Array.isArray(raw)) throw new Error("services: Service.json is not an array.");
	return raw.map((row, index) => {
		const fields = (row as { fields?: Record<string, unknown> }).fields;
		const pk = (row as { pk?: unknown }).pk;
		if (typeof pk !== "string" || fields === undefined || typeof fields.name !== "string") {
			throw new Error(`services: Service.json row ${index} is missing pk or name.`);
		}
		if (typeof fields.cost !== "string" || typeof fields.desc !== "string") {
			throw new Error(`services: '${pk}' is missing cost or desc.`);
		}
		return {
			pk,
			name: fields.name,
			desc: fields.desc,
			cost: fields.cost,
			detail: typeof fields.detail === "string" ? fields.detail : null,
		};
	});
}

/** Every Service.json row except stabling, which is already srd/item/stabling-per-day. */
export function serviceUnits(): ServiceUnit[] {
	return readServices()
		.filter((row) => row.pk !== STABLING_PK)
		.map((row) => {
			const slug = row.pk.replace(/^srd-2024_/, "");
			const detail = row.detail ?? "";
			return {
				pk: row.pk,
				slug,
				name: row.name,
				description: detail === "" ? row.desc : `${row.desc} Period: ${detail}.`,
				costCp: costCpFromGpString(row.cost),
				detail,
				entityId: `srd/service/${slug}`,
			};
		});
}

export async function buildServiceFragments(target?: AuthorTarget): Promise<{
	fragments: Record<string, string>;
	units: ChapterUnitSummary[];
}> {
	const units = serviceUnits();
	if (units.length !== 29) {
		throw new Error(`services: expected 29 service rows besides stabling, found ${units.length}.`);
	}
	const body = await driveUnitScene(
		"srd",
		[
			...itemMeasureResourceCalls(),
			...units.map((row) => ({
				toolName: "spellkave_define_entity_type" as const,
				label: `service:${row.slug}`,
				params: {
					bundle: "srd",
					id: `service/${row.slug}`,
					display_name: row.name,
					description: row.description,
					initial_states: [{ state: "srd/cost_cp", value_int: row.costCp }],
				},
			})),
		],
		target,
		{ omitRowKinds: ["resource_definitions"] },
	);
	return {
		fragments: {
			"base/equipment/services.toml":
				"# GENERATED by src/chapters/equipment/services.ts — DO NOT EDIT BY HAND.\n" +
				"# Regenerate: pnpm --filter @spellkave/srd-cc run generate\n" +
				"# Service.json costs. Stabling stays srd/item/stabling-per-day.\n\n" +
				body,
		},
		units: units.map((row) => ({
			kind: "entity_definitions",
			id: row.entityId,
			sourcePk: row.pk,
		})),
	};
}
