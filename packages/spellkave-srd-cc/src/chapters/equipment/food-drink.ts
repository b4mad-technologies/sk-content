/** Priced food and drink from the Food, Drink, and Lodging table.
 * Inn-stay and meal lifestyle rows are Service.json identities and stay
 * declared, not duplicated here.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { readGearFlavor } from "../../flavor/read";
import { CACHE_MARKDOWN_DIR } from "../../markdown/paths.ts";
import {
	markdownHeadingBlock,
	srdTextAttachmentWriteCall,
	srdTextNamespaceWriteCall,
} from "../../text";
import type { ChapterUnitSummary } from "../chapter-types.ts";
import { driveUnitScene } from "../verb-runner.ts";
import { costCpFromGpString, itemMeasureResourceCalls } from "./item-measures.ts";

export interface FoodDrinkUnit {
	slug: string;
	name: string;
	costLabel: string;
	costCp: number;
}

function costCp(label: string): number {
	const match = /^([\d,]+)\s+(GP|SP|CP)$/.exec(label);
	if (match?.[1] === undefined || match[2] === undefined) {
		throw new Error(`food-drink: cost '${label}' is not a GP/SP/CP amount.`);
	}
	const amount = match[1].replaceAll(",", "");
	const gp =
		match[2] === "GP"
			? amount
			: match[2] === "SP"
				? String(Number(amount) / 10)
				: String(Number(amount) / 100);
	return costCpFromGpString(gp);
}

function requireCell(source: string, name: string): void {
	if (!source.includes(`<td>${name}</td>`)) {
		throw new Error(`food-drink: table cell '${name}' is missing.`);
	}
}

/** Goods in the Food, Drink, and Lodging table that are not Service.json rows. */
export function foodDrinkUnits(): FoodDrinkUnit[] {
	const source = readFileSync(path.join(CACHE_MARKDOWN_DIR, "equipment.md"), "utf8");
	const rows = [
		{ slug: "ale-mug", name: "Ale (mug)", costLabel: "4 CP" },
		{ slug: "bread-loaf", name: "Bread (loaf)", costLabel: "2 CP" },
		{ slug: "cheese-wedge", name: "Cheese (wedge)", costLabel: "1 SP" },
		{ slug: "wine-common", name: "Wine (bottle), Common", costLabel: "2 SP" },
		{ slug: "wine-fine", name: "Wine (bottle), Fine", costLabel: "10 GP" },
	] as const;
	for (const row of rows) {
		if (row.slug.startsWith("wine-")) requireCell(source, "Wine (bottle)");
		else requireCell(source, row.name);
		if (!source.includes(`<td>${row.costLabel}</td>`)) {
			throw new Error(`food-drink: cost '${row.costLabel}' is missing.`);
		}
	}
	if (!source.includes("<td>Common</td>") || !source.includes("<td>Fine</td>")) {
		throw new Error("food-drink: wine Common/Fine rows are missing.");
	}
	return rows.map((row) => ({ ...row, costCp: costCp(row.costLabel) }));
}

export async function buildFoodDrinkFragments(): Promise<{
	fragments: Record<string, string>;
	units: ChapterUnitSummary[];
}> {
	const extracted = markdownHeadingBlock("equipment.md", "Food, Drink, and Lodging");
	const fragments: Record<string, string> = {};
	const units: ChapterUnitSummary[] = [];
	for (const row of foodDrinkUnits()) {
		const body = await driveUnitScene(
			"srd",
			[
				srdTextNamespaceWriteCall(),
				...itemMeasureResourceCalls(),
				{
					toolName: "spellkave_define_entity_type",
					label: `food-drink:${row.slug}`,
					params: {
						bundle: "srd",
						id: `item/${row.slug}`,
						display_name: row.name,
						description: readGearFlavor(row.slug).body,
						tags: [
							"srd.item",
							"srd.item.gear",
							...(row.slug === "bread-loaf" || row.slug === "cheese-wedge"
								? ["srd.item.food"]
								: []),
						],
						initial_states: [{ state: "srd/cost_cp", value_int: row.costCp }],
					},
				},
				srdTextAttachmentWriteCall({
					targetKind: "entity_definition",
					targetRef: `srd/item/${row.slug}`,
					extracted,
				}),
			],
			undefined,
			{ omitRowKinds: ["metadata_namespaces", "resource_definitions"] },
		);
		fragments[`base/equipment/gear/${row.slug}.toml`] =
			"# GENERATED by src/chapters/equipment/food-drink.ts — DO NOT EDIT BY HAND.\n" +
			"# Regenerate: pnpm --filter @spellkave/srd-cc run generate\n" +
			`# Cost ${row.costLabel} from cache/markdown/equipment.md Food, Drink, and Lodging.\n\n` +
			body;
		units.push({
			kind: "entity_definitions",
			id: `srd/item/${row.slug}`,
			sourcePk: "equipment.md:Food, Drink, and Lodging",
		});
	}
	return { fragments, units };
}
