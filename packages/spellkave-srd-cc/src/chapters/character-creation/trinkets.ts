/** Trinket table rows. The cell is the identity. No cost or weight is in the source. */
import { readFileSync } from "node:fs";
import path from "node:path";
import type { AuthorTarget } from "@spellkave/tool-authoring";
import { CACHE_MARKDOWN_DIR } from "../../markdown/paths.ts";
import type { ChapterUnitSummary } from "../chapter-types.ts";
import { driveUnitScene } from "../verb-runner.ts";

export interface TrinketUnit {
	roll: string;
	text: string;
	slug: string;
	entityId: string;
}

export function trinketUnits(): TrinketUnit[] {
	const source = readFileSync(path.join(CACHE_MARKDOWN_DIR, "character-creation.md"), "utf8");
	const section = source.slice(source.indexOf("## Trinkets"));
	const rows = [...section.matchAll(/<td>(\d{2})<\/td>\s*<td>([^<]+)<\/td>/g)];
	if (rows.length !== 100) {
		throw new Error(`trinkets: expected 100 table rows, found ${rows.length}.`);
	}
	return rows.map((match) => {
		const roll = match[1];
		const text = match[2]?.trim();
		if (roll === undefined || text === undefined || text === "") {
			throw new Error("trinkets: a table row was empty.");
		}
		const number = roll === "00" ? "100" : roll;
		const slug = `trinket-${number}`;
		return { roll, text, slug, entityId: `srd/trinket/${slug}` };
	});
}

export async function buildTrinketFragment(target?: AuthorTarget): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const rows = trinketUnits();
	const body = await driveUnitScene(
		"srd",
		rows.map((row) => ({
			toolName: "spellkave_define_entity_type" as const,
			label: `trinket:${row.slug}`,
			params: {
				bundle: "srd",
				id: `trinket/${row.slug}`,
				display_name: `Trinket ${row.roll}`,
				description: row.text,
			},
		})),
		target,
	);
	return {
		toml:
			"# GENERATED by src/chapters/character-creation/trinkets.ts — DO NOT EDIT BY HAND.\n" +
			"# Regenerate: pnpm --filter @spellkave/srd-cc run generate\n" +
			"# Trinkets table cells from cache/markdown/character-creation.md. No price or weight.\n\n" +
			body,
		units: rows.map((row) => ({
			kind: "entity_definitions",
			id: row.entityId,
			sourcePk: `character-creation.md:Trinkets:${row.roll}`,
		})),
	};
}
