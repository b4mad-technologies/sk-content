const GENERIC_CHECK_DC_ANCHOR =
	"playing-the-game.md § D20 Tests > Ability Checks (Typical Difficulty Classes); " +
	"derived tier grounded in rules-glossary.md § Influence [Action]";

export async function buildGenericCheckDcFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	// Loud-fail grounding guards — see generic-check-units.ts's own module
	// header (Open Question 1 finding + the Influence Checks table source).
	assertInfluenceChecksSource();
	const subjects = buildGenericCheckSubjects();
	const maxDc = maxTypicalDc();
	const blocks: string[] = [];
	const summaries: ChapterUnitSummary[] = [];
	for (const subject of subjects) {
		const id = genericCheckDcOverrideSuffix(subject);
		const resourceCall = {
			toolName: "spellkave_define_resource" as const,
			label: `resource:${id}`,
			params: {
				id,
				display_name: `${subject.displayName} — DC override`,
				min_value: 0,
				max_value: maxDc,
				initial_value: 0,
				recovery_rule: "persistent",
				description: readResourceFlavor(resourceFlavorSlug(id)).body,
				tags: [DIFFICULTY_CLASS_TAG],
			},
		};
		const fragment =
			summaries.length === 0
				? await driveDefineWithSrdText(BUNDLE_ID, resourceCall, {
						targetKind: "resource_definition",
						targetRef: `${BUNDLE_ID}/${id}`,
						extracted: markdownHeadingBlock("rules-glossary.md", "Difficulty Class"),
					})
				: await driveUnitFragment(BUNDLE_ID, resourceCall);
		blocks.push(
			`# generic-check-units.ts DC-source ladder — subject: ${subject.kind} '${subject.slug}'\n` +
				`# anchor: ${GENERIC_CHECK_DC_ANCHOR}\n` +
				fragment,
		);
		summaries.push({ kind: "resource_definitions", id: `${BUNDLE_ID}/${id}`, sourcePk: "" });
	}
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/generic.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Generic check DC-override states (design: ledger/designs/",
		"# generic-skill-check-target-dc.md § B): one resource per skill (18) plus",
		"# one per raw ability (6): skills use srd/dc/<slug>, while raw abilities",
		"# use srd/dc/ability-<code> so their natural-key suffix cannot collide",
		"# with the ability resources resolved by srd.ability.<code> tags.",
		"# Every row carries the shared srd.difficulty_class tag, whose queryable",
		"# vocabulary description contains the complete Typical DC ladder.",
		"# Bounds [0, <max Typical DC>] are read",
		"# from the cached Typical Difficulty Classes table (ability-checks-units.ts),",
		'# never hardcoded. initial_value 0 is the documented "no override" sentinel —',
		"# see generic-check-units.ts's own module header for why an UNSEEDED read",
		"# still fails closed (finding #35): this is declarative metadata,",
		"# not a free default for arbitrary entities.",
		"",
		"",
	].join("\n");
	return { toml: header + blocks.join("\n"), units: summaries };
}

/**
 * The full predicate for one shipped generic-check verb — composes
 * `genericSkillCheckExpr`/`genericAbilityCheckExpr` (generic-check-units.ts,
 * "compose, never retype") against this chapter's own concrete state ids
 * (`srd/<ability>`, `srd/level`, the subject's DC override, `srd/int`) — the ONE place
 * those bundle-qualified ids get threaded into the row-less idiom.
 */
function genericCheckPredicate(subject: GenericCheckSubject): string {
	const scoreExpr = `actor.effective('${BUNDLE_ID}/${subject.governingAbility}')`;
	const dcOverrideStateId = `${BUNDLE_ID}/${genericCheckDcOverrideSuffix(subject)}`;
	if (subject.kind === "skill") {
		if (subject.skillCapabilitySuffix === undefined) {
			throw new Error(
				`playing-the-game/index: skill subject '${subject.slug}' has no skillCapabilitySuffix.`,
			);
		}
		return genericSkillCheckExpr({
			scoreExpr,
			skillCapabilityId: `${BUNDLE_ID}/${subject.skillCapabilitySuffix}`,
			proficiencyLevelExpr: `actor.stat('${BUNDLE_ID}/${LEVEL_ID}')`,
			dcOverrideStateId,
			isInfluenceShaped: subject.isInfluenceShaped,
			targetIntStateId: subject.isInfluenceShaped ? `${BUNDLE_ID}/int` : undefined,
		});
	}
	return genericAbilityCheckExpr({ scoreExpr, dcOverrideStateId, isInfluenceShaped: false });
}

