import {
	BASELINE_SENSING_NICHE_ID,
	BUNDLE_ID,
	SENSE_LOOK_AFFORDANCE_ID,
	SENSE_LOOK_OUTCOME_ID,
	SENSE_LOOK_SAME_SUBSTRATE_AFFORDANCE_ID,
} from "../constants";

const GENESIS_REDIRECT_ANCHOR =
	"ledger/findings.md finding #49; server/src/world_interaction/" +
	"affordance_materialiser/subscription.rs's subscribe_perceiver (NOT ADR-0070, #1998); " +
	"canon-warden redirect on #2032 (not genesis — self-sufficiency instead)";

export async function buildBaselineSensingFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "outcome:sense-look",
			params: {
				bundle: BUNDLE_ID,
				kind: "outcome_templates",
				rows: [
					{
						outcome_template_id: SENSE_LOOK_OUTCOME_ID,
						bundle_id: BUNDLE_ID,
						display_name: "Look Around",
						outcome_bool: true,
						sense_query_kind: "look",
						sense_visibility: "local",
						consequence_template_id: "",
						discovery_validated: true,
						// Player-facing prose: this string is what a person READS when they use
						// "Look around" in play (sk-0m4.114, #2722 — a hosted run got the old
						// engineering blurb as its whole look-around text). The engineering
						// grounding for why this row EXISTS stays in this fragment's header
						// comment and in GENESIS_REDIRECT_ANCHOR, out of the data. Deliberately
						// place-agnostic: one universal baseline row serves every place.
						description:
							"You take a moment to look around, letting the place settle into focus " +
							"— its shape and light, who and what shares it with you, and the ways out.",
					},
				],
			},
		},
		{
			toolName: "spellkave_write_rows",
			label: "affordance:sense-look",
			params: {
				bundle: BUNDLE_ID,
				kind: "affordance_templates",
				rows: [
					{
						template_id: SENSE_LOOK_AFFORDANCE_ID,
						bundle_id: BUNDLE_ID,
						niche_id: BASELINE_SENSING_NICHE_ID,
						capability_id: "",
						display_name: "Look around",
						predicate_bool: true,
						outcome_template_id: SENSE_LOOK_OUTCOME_ID,
					},
					{
						template_id: SENSE_LOOK_SAME_SUBSTRATE_AFFORDANCE_ID,
						bundle_id: BUNDLE_ID,
						niche_id: BASELINE_SENSING_NICHE_ID,
						capability_id: "",
						display_name: "Look around (same substrate only)",
						predicate_bool: false,
						predicate_source: "actor.substrate_id == target.substrate_id",
						outcome_template_id: SENSE_LOOK_OUTCOME_ID,
					},
				],
			},
		},
	];

	const body = await driveUnitScene(BUNDLE_ID, calls);

	const units: ChapterUnitSummary[] = [
		{ kind: "outcome_templates", id: SENSE_LOOK_OUTCOME_ID, sourcePk: "" },
		{ kind: "affordance_templates", id: SENSE_LOOK_AFFORDANCE_ID, sourcePk: "" },
		{ kind: "affordance_templates", id: SENSE_LOOK_SAME_SUBSTRATE_AFFORDANCE_ID, sourcePk: "" },
	];

	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/sensing.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Self-sufficiency infra, NOT open5e content (finding #49,",
		"# ledger/findings.md; canon-warden redirect on #2032, 2026-07-28): an",
		'# srd-own baseline sensing verb chain, shape-mirrored from the "core"',
		"# bundle's own sense-look chain (one outcome_templates row + two",
		"# affordance_templates rows, no action_definitions row —",
		"# passive/PERCEIVE-class, not manipulation-dispatched). r_claim_actor's",
		"# presence trigger (subscribe_perceiver, NOT ADR-0070 — #1998) is fully generic —",
		"# it materialises whichever bundle's own outcome_templates row carries a",
		'# non-empty sense_query_kind under the "sensing" verb class',
		"# (resolve_typed_descriptor, affordance_materialiser/reconcile/",
		'# candidates.rs) — so a bundle without the "core" bundle seeded needs its',
		"# OWN copy of this chain to expose the class at all. niche_id",
		"# (srd/sense_query) is srd-own — plain authored vocabulary, not",
		"# kernel-meaningful (see this fragment's own doc comment for the full",
		"# grep-verified grounding).",
		"",
		`# anchor: ${GENESIS_REDIRECT_ANCHOR}`,
		"",
		"",
	].join("\n");
	return { toml: header + body, units };
}

