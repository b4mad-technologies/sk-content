import { readResourceFlavor } from "../../../flavor/read";
import {
	markdownHeadingBlock,
	srdTextAttachmentWriteCall,
	withSrdTextNamespace,
} from "../../../text";
import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene, type VerbCall } from "../../verb-runner";
import {
	AC_DISPLAY_NAME,
	AC_ID,
	AC_RESOURCE_ID,
	AC_RESOURCE_INITIAL,
	AC_RESOURCE_MAX,
	AC_RESOURCE_MIN,
	acModifierTargetRow,
} from "../armor-class-units";
import { BUNDLE_ID } from "../constants";

const ARMOR_CLASS_ANCHOR = "playing-the-game.md § Attack Rolls > Armor Class";

export async function buildArmorClassFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_define_resource",
			label: "resource:ac",
			params: {
				id: AC_ID,
				display_name: AC_DISPLAY_NAME,
				min_value: AC_RESOURCE_MIN,
				max_value: AC_RESOURCE_MAX,
				initial_value: AC_RESOURCE_INITIAL,
				recovery_rule: "persistent",
				description: readResourceFlavor("ac").body,
				tags: [],
			},
		},
		{
			toolName: "spellkave_write_rows",
			label: "modifier-target:ac",
			params: {
				bundle: BUNDLE_ID,
				kind: "modifier_target_definitions",
				rows: [acModifierTargetRow()],
			},
		},
	];
	const body = await driveUnitScene(
		BUNDLE_ID,
		withSrdTextNamespace([
			...calls,
			srdTextAttachmentWriteCall({
				targetKind: "resource_definition",
				targetRef: AC_RESOURCE_ID,
				extracted: markdownHeadingBlock("rules-glossary.md", "Armor Class"),
			}),
		]),
	);
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/armor-class.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Central Armor Class rule: the srd/ac resource and its modifier axis.",
		"# Equipment, cover, magic, and other content consume this shared fact;",
		"# they do not own or redefine it in their generated fixture.",
		"",
		`# anchor: ${ARMOR_CLASS_ANCHOR}`,
		"",
		"",
	].join("\n");
	return {
		toml: header + body,
		units: [
			{ kind: "resource_definitions", id: AC_RESOURCE_ID, sourcePk: "" },
			{ kind: "modifier_target_definitions", id: AC_RESOURCE_ID, sourcePk: "" },
		],
	};
}
