import { srdTextNamespaceWriteCall } from "../../../text";
import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene } from "../../verb-runner";
import { BUNDLE_ID } from "../constants";
import { buildTagValueDefinitionUnits } from "../tag-value-vocabulary";

/** Render the package's exact, manifest-owned tag vocabulary through AUTHOR. */
export async function buildTagValueVocabularyFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const definitions = buildTagValueDefinitionUnits();
	const fragment = await driveUnitScene(
		BUNDLE_ID,
		[
			srdTextNamespaceWriteCall(),
			{
				toolName: "spellkave_write_rows",
				label: "tag-value-vocabulary",
				params: {
					bundle: BUNDLE_ID,
					kind: "tag_value_definitions",
					rows: definitions.map(({ tag, prefix, description }) => ({
						tag,
						prefix,
						bundle_id: BUNDLE_ID,
						description,
					})),
				},
			},
		],
		undefined,
		{
			onlyTagValueDefinitionTags: definitions.map((definition) => definition.tag),
			retainSrdTextNamespace: true,
		},
	);
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/tag-vocabulary.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Exact tag vocabulary for every tag value this bundle currently emits.",
		"# The srd.ability_score description embeds all seven meaning bands from",
		"# cache/open5e/Rule.json pk srd-2024_the-six-abilities_ability-scores.",
		"# The srd.difficulty_class description embeds all six Typical Difficulty",
		"# Classes from pk srd-2024_d20-tests_ability-checks.",
		"# The three srd.travel_pace.* descriptions embed the complete Travel Pace",
		"# table and effects from pk srd-2024_exploration_travel.",
		"# The 14 Creature Type descriptions are sourced verbatim from",
		"# cache/open5e/CreatureTypeDescription.json (CC-BY-4.0). These rows are",
		"# vocabulary metadata only; they do not add behaviour or a new target niche.",
		"",
		"",
	].join("\n");
	return {
		toml: header + fragment,
		units: definitions.map((definition) => ({
			kind: "tag_value_definitions",
			id: definition.tag,
			sourcePk: definition.sourcePk,
		})),
	};
}
