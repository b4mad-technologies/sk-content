import type { ChapterUnitSummary } from "../../chapter-types";
import type { VerbCall } from "../../verb-runner";
import { driveUnitScene } from "../../verb-runner";
import { BUNDLE_ID } from "../constants";
import {
	buildPlayerCharacterCapabilityGrantRows,
	buildPlayerCharacterCapabilityGrantUnits,
} from "../player-character-identity-units";

/**
 * The PC-only verb package, authored once against `srd.player_character`.
 *
 * Written through `spellkave_write_rows` rather than a bespoke verb —
 * `tag_capability_grant` is a two-column grant rule with no narrative
 * surface of its own, the same reason `fragments/tag-vocabulary.ts` writes
 * its vocabulary rows generically.
 *
 * Driven as a SCENE rather than a single call because this is the first
 * fragment in the bundle whose rows reference `capability_definitions` that
 * a DIFFERENT fragment ships (dodge, drop-prone, rest, heroic-inspiration,
 * advancement). `MF-VAL-254` is a same-bundle check, so each referenced
 * capability is re-declared into this throwaway workspace and then dropped
 * from the emitted fragment via `omitRowKinds` — the same seed-then-strip
 * idiom the tag-value and macro seeds already use. The stripped
 * re-declarations are byte-identical no-ops against the rows their owning
 * fragments ship; nothing here can silently redefine a capability, because
 * nothing here survives into the manifest.
 */
export async function buildPlayerCharacterIdentityFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const units = buildPlayerCharacterCapabilityGrantUnits();
	const seedCalls: VerbCall[] = units.map((unit) => ({
		toolName: "spellkave_define_capability",
		label: `seed-capability:${unit.capabilityId}`,
		params: {
			bundle: BUNDLE_ID,
			id: unit.capabilityId.slice(`${BUNDLE_ID}/`.length),
			actor_kind: "entity",
			display_name: unit.capabilityId,
			description: "sk-bwd seed-then-strip placeholder — never emitted (see this module's header).",
		},
	}));
	const fragment = await driveUnitScene(
		BUNDLE_ID,
		[
			...seedCalls,
			{
				toolName: "spellkave_write_rows",
				label: "player-character-identity-grants",
				params: {
					bundle: BUNDLE_ID,
					kind: "tag_capability_grant",
					rows: buildPlayerCharacterCapabilityGrantRows(),
				},
			},
		],
		undefined,
		{ omitRowKinds: ["capability_definitions", "capability_definition_tag"] },
	);
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/player-character-identity.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# The PC IDENTITY -> capability bridge (sk-bwd). Each row says: while an",
		"# entity bears srd.player_character, it may ACT with this PC-only capability. Read live",
		"# by capability_ids_for_actor alongside the equipped-item, place, and",
		"# condition bridges — never seeded onto a placed instance, so removing",
		"# the tag removes the verbs with it.",
		"#",
		"# Per-verb rationale (why identity, not training/kit/place):",
		...units.map((unit) => `#   ${unit.capabilityId} — ${unit.rationale}`),
		"#",
		"# Deliberately NOT granted here: universal creature attempts (walking,",
		"# attacks, Dodge, Help, Drop Prone, rests, and srd/check/*) derive from",
		"# srd.creature in creature-identity.toml; skills remain trained",
		"# proficiencies from class/background choices; class",
		"# features (sourced live from srd.advancement_grant metadata).",
		"",
		"",
	].join("\n");
	return {
		toml: header + fragment,
		units: units.map((unit) => ({
			kind: "tag_capability_grant",
			id: `${unit.tag}:${unit.capabilityId}`,
			sourcePk: "",
		})),
	};
}
