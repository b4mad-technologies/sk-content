export async function buildSkillsFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const units = buildSkillUnits();
	const blocks: string[] = [];
	const summaries: ChapterUnitSummary[] = [];
	for (const unit of units) {
		const fragment = await driveUnitFragment(BUNDLE_ID, {
			toolName: "spellkave_define_capability",
			label: `capability:skill/${unit.slug}`,
			params: {
				id: `skill/${unit.slug}`,
				actor_kind: "entity",
				display_name: unit.displayName,
				description: unit.description,
				tags: ["srd.skill", `srd.ability.${unit.governingAbility}`],
			},
		});
		const abilityProvenance =
			`# ability tag ("srd.ability.${unit.governingAbility}") sourced from: playing-the-game.md's ` +
			"Skill Proficiencies table, Ability column (cache/markdown/playing-the-game.md, parsed by " +
			"src/markdown/playing-the-game.ts) — NOT from SkillDescription.json, which carries no ability field.";
		blocks.push(
			`${provenanceComment("SkillDescription.json", unit.sourcePk, SKILLS_ANCHOR)}${abilityProvenance}\n` +
				fragment,
		);
		summaries.push({
			kind: "capability_definitions",
			id: `${BUNDLE_ID}/skill/${unit.slug}`,
			sourcePk: unit.sourcePk,
		});
	}
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/identity.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Skills identity list (playing-the-game.md § Proficiency > Skill",
		"# Proficiencies). Identity fields (id, display name, description) are",
		"# sourced from cache/open5e/SkillDescription.json (18 records, CC-BY-4.0);",
		"# the governing-ability tag is sourced from the SAME chapter's cached",
		"# markdown Skill Proficiencies table (cache/markdown/playing-the-game.md,",
		"# parsed by src/markdown/playing-the-game.ts) — SkillDescription.json",
		"# carries no ability field at all. capability_definitions shape matches",
		"# world-fixtures/srd/base/origin-mechanics.toml's srd/skill/insight and",
		'# srd/skill/religion rows: bundle "srd", ids srd/skill/<slug>, tags',
		'# ["skill", "srd.ability.<code>"]. IDENTITY ONLY — the proficiency-application',
		"# mechanic (bonus applies when proficient) is deferred to a later slice;",
		"# see ledger/playing-the-game.md.",
		"",
		"",
	].join("\n");
	return { toml: header + blocks.join("\n"), units: summaries };
}
