function provenanceComment(sourceFile: string, pk: string, anchor: string): string {
	return [`# open5e: ${sourceFile} pk=${pk}`, `# anchor: ${anchor}`, ""].join("\n");
}

export async function buildAbilitiesFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const units = buildAbilityUnits();
	const readerMetadata = readSixAbilitiesReaderFragmentMetadata();
	const blocks: string[] = [];
	const summaries: ChapterUnitSummary[] = [];
	for (const [index, unit] of units.entries()) {
		const ownsReaderMetadata = index === 0;
		const fragment = await driveUnitScene(
			BUNDLE_ID,
			[
				...(ownsReaderMetadata
					? [
							metadataCall("docs-the-six-abilities", BUNDLE_ID, [
								{
									target: "manifest",
									key: "docs",
									value: { "the-six-abilities": readerMetadata },
								},
							]),
						]
					: []),
				srdTextNamespaceWriteCall(),
				{
					toolName: "spellkave_define_resource",
					label: `resource:${unit.code}`,
					params: {
						id: unit.code,
						display_name: unit.displayName,
						min_value: 0,
						max_value: 30,
						initial_value: 10,
						recovery_rule: "persistent",
						description: readResourceFlavor(unit.code).body,
						tags: ["srd.ability_score"],
					},
				},
				srdTextAttachmentWriteCall({
					targetKind: "resource_definition",
					targetRef: `${BUNDLE_ID}/${unit.code}`,
					extracted: open5eStringField("AbilityDescription.json", unit.sourcePk),
				}),
				{
					toolName: "spellkave_write_rows",
					label: `modifier-target:${unit.code}`,
					params: {
						bundle: BUNDLE_ID,
						kind: "modifier_target_definitions",
						rows: [abilityModifierTargetRow(unit.code)],
					},
				},
			],
			undefined,
			{ retainMetadata: ownsReaderMetadata },
		);
		blocks.push(
			provenanceComment("AbilityDescription.json", unit.sourcePk, ABILITIES_ANCHOR) + fragment,
		);
		summaries.push(
			{
				kind: "resource_definitions",
				id: `${BUNDLE_ID}/${unit.code}`,
				sourcePk: unit.sourcePk,
			},
			{
				kind: "modifier_target_definitions",
				id: `${BUNDLE_ID}/${unit.code}`,
				sourcePk: unit.sourcePk,
			},
		);
	}
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/identity.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# The Six Abilities identity list (playing-the-game.md § The Six Abilities),",
		"# sourced from cache/open5e/AbilityDescription.json (6 records, CC-BY-4.0).",
		"# resource_definitions shape matches world-fixtures/srd/base/resources.toml's",
		'# ability-score rows: bundle "srd", ids srd/str|dex|con|int|wis|cha, bounds',
		'# [0,30], initial 10, recovery_rule "persistent". Mechanic (ability',
		"# modifiers, etc.) is deferred to a later slice — see ledger/playing-the-game.md.",
		"#",
		"# Deliberate divergence from the sister: the sister's ability-score rows",
		'# also carry a "core" tag; this bundle drops it (AGENTS.md "question, never',
		'# copy" — no consumer (DSL predicate, server read, test, SDK surface)',
		'# queries a "core" tag on a resource anywhere, and this bundle ships',
		'# depends_on = [] so "core" would misleadingly suggest the core bundle).',
		"",
		"",
	].join("\n");
	return { toml: header + blocks.join("\n"), units: summaries };
}

export async function buildLevelFragment(): Promise<{ toml: string; units: ChapterUnitSummary[] }> {
	assertLevelProvenanceSource();
	const fragment = await driveDefineWithSrdText(
		BUNDLE_ID,
		{
			toolName: "spellkave_define_resource",
			label: `resource:${LEVEL_ID}`,
			params: {
				id: LEVEL_ID,
				display_name: LEVEL_DISPLAY_NAME,
				min_value: MIN_CHARACTER_LEVEL,
				max_value: MAX_CHARACTER_LEVEL,
				initial_value: INITIAL_CHARACTER_LEVEL,
				recovery_rule: "persistent",
				description: readResourceFlavor("level").body,
				tags: [],
			},
		},
		{
			targetKind: "resource_definition",
			targetRef: `${BUNDLE_ID}/${LEVEL_ID}`,
			extracted: markdownHeadingBlock("character-creation.md", "Level Advancement"),
		},
	);
	// sk-84i.4: the baked-per-entity Proficiency Bonus STAT — see
	// `modifier-units.ts`'s own `PROFICIENCY_BONUS_STATE_ID` doc comment for
	// the full macro-vs-stat rationale and the ADR-0035 fail-closed
	// missing-stat decision. Every combatant that uses `weapon-attack-
	// units.ts`'s generic Melee/Ranged Attack archetype (`creature-units.ts`'s
	// 331 creatures, this chapter's own proof-scene combatants) seeds this
	// value explicitly, derived from CR (creatures) or level (PC-like
	// actors) via `expectedProficiencyBonus` — never a bare literal.
	const proficiencyBonusFragment = await driveUnitFragment(BUNDLE_ID, {
		toolName: "spellkave_define_resource",
		label: "resource:proficiency_bonus",
		params: {
			id: PROFICIENCY_BONUS_ID,
			display_name: PROFICIENCY_BONUS_STATE_DISPLAY_NAME,
			min_value: PROFICIENCY_BONUS_STATE_MIN,
			max_value: PROFICIENCY_BONUS_STATE_MAX,
			initial_value: PROFICIENCY_BONUS_STATE_MIN,
			recovery_rule: "persistent",
			description: readResourceFlavor("proficiency-bonus").body,
			tags: [],
		},
	});
	const reachFragment = await driveUnitFragment(BUNDLE_ID, {
		toolName: "spellkave_define_resource",
		label: "resource:reach_mm",
		params: {
			id: REACH_RESOURCE_LOCAL_ID,
			display_name: "Reach",
			min_value: 0,
			max_value: MAX_REACH_MM,
			initial_value: STANDARD_REACH_MM,
			recovery_rule: "persistent",
			description: readResourceFlavor("reach-mm").body,
			tags: [],
		},
	});
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/identity.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Character Level (playing-the-game.md § Proficiency): the srd/level",
		"# resource the Proficiency Bonus macro (srd/proficiency_bonus) reads.",
		"# Sourced from THIS chapter's own lead",
		"# paragraph (\"A character's Proficiency Bonus increases as the character",
		'# gains levels") — no open5e pk exists for it (identity-only, no table to',
		"# parse), so there is no provenance-comment pk/anchor pair below, only the",
		"# markdown anchor. Bounds [1,20] adopted from the sister precedent",
		"# (world-fixtures/srd/base/advancement.toml's srd/level row) — see",
		"# level-units.ts's own module header for the full provenance + divergence",
		'# record (the sister\'s "core"/"advancement" tags are deliberately dropped).',
		"#",
		"# ALSO in this fragment (sk-84i.4): srd/proficiency_bonus as a STAT",
		"# (resource_definitions), distinct from the SAME-id MACRO defined in",
		"# fragments/macros.ts — modifier-units.ts's own PROFICIENCY_BONUS_STATE_ID",
		"# doc comment has the full rationale (baked per-entity fact for combatants",
		"# with no live level/CR fact to feed the macro, e.g. every creature).",
		"# This fragment also defines srd/reach_mm: standard 5-foot (1524 mm)",
		"# reach, explicitly seeded on every srd.creature definition. Its [0,9144]",
		"# bound covers the 30-foot maximum in CreatureActionAttack.json; the shipped",
		"# Reach property adds one more standard reach in the attack predicate.",
		"",
		`# anchor: ${LEVEL_ANCHOR}`,
		"",
		"",
	].join("\n");
	return {
		toml: header + fragment + proficiencyBonusFragment + reachFragment,
		units: [
			{ kind: "resource_definitions", id: `${BUNDLE_ID}/${LEVEL_ID}`, sourcePk: "" },
			{ kind: "resource_definitions", id: PROFICIENCY_BONUS_STATE_ID, sourcePk: "" },
			{ kind: "resource_definitions", id: REACH_RESOURCE_ID, sourcePk: "" },
		],
	};
}

