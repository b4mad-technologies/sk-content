import type { AuthorTarget } from "@spellkave/tool-authoring";

import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitFragment, type VerbCall } from "../../verb-runner";
import { ACTION_MECHANIC_DECISIONS, buildActionUnits } from "../actions-units";
import { BUNDLE_ID } from "../constants";

const ACTIONS_ANCHOR = "playing-the-game.md § Actions";

function capabilityCall(unit: {
	slug: string;
	displayName: string;
	description: string;
}): VerbCall {
	return {
		toolName: "spellkave_define_capability",
		label: `capability:action/${unit.slug}`,
		params: {
			id: `action/${unit.slug}`,
			actor_kind: "entity",
			display_name: unit.displayName,
			description: unit.description,
			tags: ["srd.action"],
		},
	};
}

export function attackCapabilityCall(): VerbCall {
	const attack = buildActionUnits().find((unit) => unit.slug === "attack");
	if (attack === undefined) {
		throw new Error("playing-the-game/actions: Attack action identity is missing.");
	}
	return capabilityCall(attack);
}

export async function buildActionsFragment(
	_target?: AuthorTarget,
): Promise<{ toml: string; units: ChapterUnitSummary[] }> {
	const units = buildActionUnits();
	const blocks: string[] = [];
	const summaries: ChapterUnitSummary[] = [];
	for (const unit of units) {
		const decision = ACTION_MECHANIC_DECISIONS[unit.slug];
		if (decision === undefined) {
			throw new Error(
				`playing-the-game/actions: no mechanic decision recorded for action '${unit.slug}'.`,
			);
		}
		const fragment = await driveUnitFragment(BUNDLE_ID, capabilityCall(unit));
		const decisionNote =
			unit.slug === "attack"
				? "The generic Attack identity is catalogued here; its Unarmed Strike Damage variant is generated in attacks.toml."
				: decision.note;
		blocks.push(
			`# markdown: playing-the-game.md § Actions (no open5e pk — see module header)\n` +
				`# anchor: ${ACTIONS_ANCHOR}\n` +
				`# mechanic decision (${decision.status}): ${decisionNote}\n` +
				fragment,
		);
		summaries.push({
			kind: "capability_definitions",
			id: `${BUNDLE_ID}/action/${unit.slug}`,
			sourcePk: "",
		});
	}
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/actions.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Actions identity list (playing-the-game.md § Actions: the 12 named",
		"# actions). Sourced from the cached chapter markdown's own Actions table",
		"# (no open5e pk exists for this section — ledger observation 3's STEP-2",
		"# follow-up). capability_definitions shape + srd/action/<slug> id convention",
		"# match the sister's own precedent: world-fixtures/srd/base/mounts.toml's",
		"# srd/action/mount and srd/action/dismount rows. creature-identity.toml",
		"# grants the three entries with shipped verbs (Attack, Dodge, Help); the",
		"# remaining identities stay ungranted until their mechanics exist.",
		"# Concrete combat variants live in attacks.toml. Weapon variants share the",
		"# Attack capability; their offer predicates require a wielded item with the",
		"# matching range tag and source-backed damage/range facts.",
		"",
		"",
	].join("\n");
	return { toml: header + blocks.join("\n"), units: summaries };
}
