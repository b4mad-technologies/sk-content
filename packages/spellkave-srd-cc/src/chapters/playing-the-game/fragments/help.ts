import type { AuthorTarget } from "@spellkave/tool-authoring";
import { dsl } from "@spellkave/world-author";

import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene, type VerbCall } from "../../verb-runner";
import { PRIMARY_CHANNEL_ID, TURN_START_BOUNDARY_ID } from "../action-economy-units";
import { BUNDLE_ID } from "../constants";
import {
	REMOVE_POLICY_INDEPENDENT_LIFETIME_LOCAL_ID,
	STACKING_SINGLE_LOCAL_ID,
} from "../cover-units";
import { CREATURE_NICHE_TAG } from "../creature-type-units";
import {
	ABILITY_CHECK_RESOLUTION_SCOPE_ID,
	resolutionScopeModifierTargetRow,
} from "../resolution-scope-units";
import { ROLL_BIAS_ADVANTAGE_TAG } from "../tag-value-vocabulary";

export const HELP_ACTION_ID = `${BUNDLE_ID}/help`;
export const HELP_CAPABILITY_ID = `${BUNDLE_ID}/action/help`;
export const HELP_CONDITION_ID = `${BUNDLE_ID}/condition/helped`;
export const HELP_ADVANTAGE_MODIFIER_ID = `${BUNDLE_ID}/condition/helped/ability-check-advantage`;

/**
 * Help [Action], `cache/markdown/rules-glossary.md:856-861`.
 *
 * The source grants Advantage on the ally's next check with a chosen skill or
 * tool and expires at the start of the helper's next turn. This first generic
 * surface cannot yet consume a condition after exactly one matching check or
 * carry the chosen proficiency as an invocation parameter. It therefore
 * grants Advantage on actor-scoped ability checks until the helped creature's
 * next `turn_start`; the approximation is explicit in generated content and
 * the chapter ledger rather than silently presented as exact.
 */
export async function buildHelpFragment(
	target?: AuthorTarget,
): Promise<{ toml: string; units: ChapterUnitSummary[] }> {
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "modifier-target:ability-check",
			params: {
				bundle: BUNDLE_ID,
				kind: "modifier_target_definitions",
				rows: [resolutionScopeModifierTargetRow(ABILITY_CHECK_RESOLUTION_SCOPE_ID)],
			},
		},
		{
			toolName: "spellkave_define_condition",
			label: "condition:helped",
			params: {
				bundle: BUNDLE_ID,
				id: "condition/helped",
				display_name: "Helped",
				gate_predicate_source: dsl`1 == 1`,
				description:
					"Help approximation: ability checks made by this creature have Advantage " +
					"until the start of its next turn. SRD 5.2.1 instead consumes the benefit " +
					"on the next chosen skill/tool check and expires it at the helper's next turn; " +
					"one-use and chosen-proficiency routing remain deferred.",
				remove_time_policy: `${BUNDLE_ID}/${REMOVE_POLICY_INDEPENDENT_LIFETIME_LOCAL_ID}`,
				stacking_rule: `${BUNDLE_ID}/${STACKING_SINGLE_LOCAL_ID}`,
				modifiers: [
					{
						id: "condition/helped/ability-check-advantage",
						display_name: "Help: Advantage on ability checks",
						applies_to: ABILITY_CHECK_RESOLUTION_SCOPE_ID,
						modifier_expression_source: dsl`let unused = 0; unused`,
						delta_kind: "Advantage",
						tags: [ROLL_BIAS_ADVANTAGE_TAG],
					},
				],
			},
		},
		{
			toolName: "spellkave_define_action_verb",
			label: "action:help",
			params: {
				bundle: BUNDLE_ID,
				id: "help",
				required_capability: HELP_CAPABILITY_ID,
				niche_id: CREATURE_NICHE_TAG,
				display_name: "Help",
				description:
					"Help a nearby ally's ability check; the helped condition is a documented " +
					"turn-bound approximation of the SRD's chosen-proficiency, next-check benefit.",
				self_eligible: false,
				self_only: false,
				non_steering: true,
				spends_channel: PRIMARY_CHANNEL_ID,
				cost_time_ms: 0,
				consequence: {
					description: "Apply the Helped condition to the target ally.",
					frame_writes: [
						{
							ApplyStatus: {
								target_kind: "entity",
								target_ref: "TargetActor",
								condition_definition_id: HELP_CONDITION_ID,
								expires_at_boundary: {
									boundary_id: TURN_START_BOUNDARY_ID,
									owner_actor: "TargetActor",
								},
							},
						},
					],
				},
			},
		},
	];

	const body = await driveUnitScene(BUNDLE_ID, calls, target);
	const units: ChapterUnitSummary[] = [
		{
			kind: "modifier_target_definitions",
			id: ABILITY_CHECK_RESOLUTION_SCOPE_ID,
			sourcePk: "",
		},
		{ kind: "condition_definitions", id: HELP_CONDITION_ID, sourcePk: "" },
		{ kind: "modifier_templates", id: HELP_ADVANTAGE_MODIFIER_ID, sourcePk: "" },
		{ kind: "action_definitions", id: HELP_ACTION_ID, sourcePk: "" },
		{ kind: "consequence_templates", id: `${HELP_ACTION_ID}/success`, sourcePk: "" },
		{ kind: "outcome_templates", id: `${HELP_ACTION_ID}/outcome`, sourcePk: "" },
		{ kind: "affordance_templates", id: `${HELP_ACTION_ID}/affordance`, sourcePk: "" },
	];
	// pattern: condition-grant-and-suppression
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/help.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"# pattern: condition-grant-and-suppression",
		"#",
		"# Help [Action], cache/markdown/rules-glossary.md:856-861.",
		"# One-use/chosen-proficiency semantics are explicitly approximated by an",
		"# actor-scoped ability-check bias expiring at the helped actor's turn_start.",
		"",
		"",
	].join("\n");
	return { toml: header + body, units };
}
