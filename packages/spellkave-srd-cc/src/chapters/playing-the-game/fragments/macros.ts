import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitFragment } from "../../verb-runner";
import { ATTACK_ROLL_HITS_MACRO_ID, BASE_AC_MACRO_ID } from "../attack-roll-units";
import { BUNDLE_ID } from "../constants";
import { DC_OR_MACRO_ID } from "../generic-check-units";
import { dslMacroDefinitionRows } from "../macro-units";
import {
	ABILITY_MODIFIER_MACRO_ID,
	ABILITY_MODIFIERS_RULE_PK,
	PROFICIENCY_BONUS_MACRO_ID,
} from "../modifier-units";
import { TAKES_TURN_MACRO_ID } from "../order-of-combat-units";

export async function buildMacrosFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const body = await driveUnitFragment(
		BUNDLE_ID,
		{
			toolName: "spellkave_write_rows",
			label: "dsl-macros",
			params: {
				bundle: BUNDLE_ID,
				kind: "dsl_macro_definitions",
				rows: dslMacroDefinitionRows(),
			},
		},
		{
			retainDslMacroDefinitions: true,
			seedDslMacroDefinitions: false,
		},
	);
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/macros.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Central catalog of reusable, typed SRD DSL macros.",
		"# Macro bodies are leaves; consumers may compose them at the call site.",
		"",
		"",
	].join("\n");
	return {
		toml: header + body,
		units: [
			{
				kind: "dsl_macro_definitions",
				id: ABILITY_MODIFIER_MACRO_ID,
				sourcePk: ABILITY_MODIFIERS_RULE_PK,
			},
			{ kind: "dsl_macro_definitions", id: PROFICIENCY_BONUS_MACRO_ID, sourcePk: "" },
			{ kind: "dsl_macro_definitions", id: DC_OR_MACRO_ID, sourcePk: "" },
			{ kind: "dsl_macro_definitions", id: BASE_AC_MACRO_ID, sourcePk: "" },
			{ kind: "dsl_macro_definitions", id: ATTACK_ROLL_HITS_MACRO_ID, sourcePk: "" },
			{ kind: "dsl_macro_definitions", id: TAKES_TURN_MACRO_ID, sourcePk: "" },
		],
	};
}
