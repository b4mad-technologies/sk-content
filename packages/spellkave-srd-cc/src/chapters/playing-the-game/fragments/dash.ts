import type { AuthorTarget } from "@spellkave/tool-authoring";

import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene, type VerbCall } from "../../verb-runner";
import { MOVEMENT_CHANNEL_ID, PRIMARY_CHANNEL_ID } from "../action-economy-units";
import { BUNDLE_ID } from "../constants";

export const DASH_ACTION_ID = `${BUNDLE_ID}/dash`;
export const DASH_CAPABILITY_ID = `${BUNDLE_ID}/action/dash`;
export const DASH_NICHE_ID = `capability:${DASH_CAPABILITY_ID}`;

/**
 * Dash [Action] (`cache/markdown/rules-glossary.md:664-668`, Rules
 * Definitions > Dash): "When you take the Dash action, you gain extra
 * movement for the current turn. The increase equals your Speed after
 * applying any modifiers." (The "special speed" clause — Fly/Swim Speed in
 * place of walking Speed — is not modelled: this package's movement channel
 * is a single shared time pool regardless of which speed resource an edge
 * reads, so granting the pool already covers whichever speed the actor's
 * next move draws on; there is no separate per-mode pool to choose between.)
 *
 * Previously identity-only (`actions-units.ts`'s own `ACTION_MECHANIC_
 * DECISIONS.dash`, "deferred-other-chapter" — no movement/Speed unit existed
 * yet to own the mechanic). sk-0m4.123 parts 1+2 shipped that unit
 * (`srd/economy_channel/movement`, `action-economy-units.ts`); this fragment
 * is the deferred mechanic landing.
 *
 * pattern: extra-action-budget
 * → packages/spellkave-world-author/docs/patterns/extra-action-budget.md
 * Same shape Action Surge proves (`fighter-units.ts`/`classes/index.ts`
 * `buildActionSurgeFragment`): `ModifyChannel` with `delta_source` omitted
 * grants exactly one full pool of the named channel — here
 * `srd/economy_channel/movement` instead of Action Surge's Primary channel.
 * Spends the Primary action (`cost_time_ms = 0` on a `spends_channel` means
 * "one full pool", the same convention Dodge's own action already uses),
 * then grants one full extra Movement pool for the SAME window.
 *
 * `DASH_CAPABILITY_ID` reuses the identity capability row `fragments/
 * actions.ts` already emits for every one of the 12 named actions
 * (`srd/action/dash`) rather than defining a second one — Dodge's own
 * fragment does the same thing for `srd/action/dodge`.
 */
export async function buildDashFragment(
	target?: AuthorTarget,
): Promise<{ toml: string; units: ChapterUnitSummary[] }> {
	const calls: VerbCall[] = [
		// actor-carried-verbs D1/D7 amendment (ruling bead sk-rd0, V1): Dash's
		// own `capability:*` synthetic niche has no niche_definitions row
		// until now — same dead-content shape `fragments/dodge.ts`'s own
		// header documents. `provider: "actor"` revives it as a universal
		// self-verb.
		{
			toolName: "spellkave_write_rows",
			label: "niche:dash",
			params: {
				bundle: BUNDLE_ID,
				kind: "niche_definitions",
				rows: [
					{
						niche_id: DASH_NICHE_ID,
						bundle_id: BUNDLE_ID,
						display_name: "Dash (self)",
						description:
							"actor-carried-verbs D1/D7 (ruling bead sk-rd0): revives Dash as a universal " +
							"self-verb — see fragments/dodge.ts's own header for the full V1 dead-content " +
							"finding this applies identically to.",
						predicate_source: "",
						provider: "actor",
					},
				],
			},
		},
		// pattern: extra-action-budget
		// → packages/spellkave-world-author/docs/patterns/extra-action-budget.md
		{
			toolName: "spellkave_define_action_verb",
			label: "action:dash",
			params: {
				bundle: BUNDLE_ID,
				id: "dash",
				required_capability: DASH_CAPABILITY_ID,
				niche_id: DASH_NICHE_ID,
				display_name: "Dash",
				description:
					"Take the Dash action (rules-glossary.md:664-668): spend your action, then gain " +
					"one full extra Movement pool for the current turn.",
				self_eligible: true,
				self_only: true,
				spends_channel: PRIMARY_CHANNEL_ID,
				cost_time_ms: 0,
				consequence: {
					description: "Grant one full extra Movement pool for the current turn.",
					frame_writes: [
						{
							ModifyChannel: {
								actor: "Actor",
								channel: MOVEMENT_CHANNEL_ID,
							},
						},
					],
				},
			},
		},
	];
	const body = await driveUnitScene(BUNDLE_ID, calls, target);
	const units: ChapterUnitSummary[] = [
		{ kind: "niche_definitions", id: DASH_NICHE_ID, sourcePk: "" },
		{
			kind: "action_definitions",
			id: DASH_ACTION_ID,
			sourcePk: "cache/markdown/rules-glossary.md:664-668",
		},
		{ kind: "consequence_templates", id: `${DASH_ACTION_ID}/success`, sourcePk: "" },
		{ kind: "outcome_templates", id: `${DASH_ACTION_ID}/outcome`, sourcePk: "" },
		{ kind: "affordance_templates", id: `${DASH_ACTION_ID}/affordance`, sourcePk: "" },
	];
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/dash.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"# pattern: extra-action-budget",
		"# → packages/spellkave-world-author/docs/patterns/extra-action-budget.md",
		"#",
		"# Dash [Action], cache/markdown/rules-glossary.md:664-668. Spends the",
		"# Primary action, then ModifyChannel-grants one full",
		"# srd/economy_channel/movement pool for the current turn (sk-0m4.123's",
		"# own movement-budget channel).",
		'# actor-carried-verbs D1/D7 (sk-rd0): niche/dash\'s provider="actor" row',
		"# revives this as a universal self-verb.",
		"",
		"",
	].join("\n");
	return { toml: header + body, units };
}
