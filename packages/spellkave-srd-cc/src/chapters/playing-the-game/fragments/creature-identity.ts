// pattern: identity-tag-capability-grant
import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene, type VerbCall } from "../../verb-runner";
import { BUNDLE_ID } from "../constants";
import {
	buildCreatureCapabilityGrantRows,
	buildCreatureCapabilityGrantUnits,
} from "../creature-identity-units";

/** Render the stable creature-identity → universal-attempt bridge. */
export async function buildCreatureIdentityFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const units = buildCreatureCapabilityGrantUnits();
	const seedCalls: VerbCall[] = units.map((unit) => ({
		toolName: "spellkave_define_capability",
		label: `seed-capability:${unit.capabilityId}`,
		params: {
			bundle: BUNDLE_ID,
			id: unit.capabilityId.slice(`${BUNDLE_ID}/`.length),
			actor_kind: "entity",
			display_name: unit.capabilityId,
			description:
				"Creature identity seed-then-strip placeholder — never emitted (see this module's header).",
		},
	}));
	const fragment = await driveUnitScene(
		BUNDLE_ID,
		[
			...seedCalls,
			{
				toolName: "spellkave_write_rows",
				label: "creature-identity-grants",
				params: {
					bundle: BUNDLE_ID,
					kind: "tag_capability_grant",
					rows: buildCreatureCapabilityGrantRows(),
				},
			},
		],
		undefined,
		{ omitRowKinds: ["capability_definitions", "capability_definition_tag"] },
	);
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/creature-identity.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Stable srd.creature identity grants the universal attempts this bundle",
		"# actually implements. Equipment supplies weapon-specific attacks;",
		"# srd/skill/* remains proficiency only; srd.monster grants nothing.",
		"# Unimplemented Actions and movement modes have no grant row.",
		"#",
		"# Per-capability rationale:",
		...units.map((unit) => `#   ${unit.capabilityId} — ${unit.rationale}`),
		"",
		"",
	].join("\n");
	return {
		toml: header + fragment,
		units: units.map((unit) => ({
			kind: "tag_capability_grant",
			id: `${unit.tag}:${unit.capabilityId}`,
			sourcePk: "",
		})),
	};
}
