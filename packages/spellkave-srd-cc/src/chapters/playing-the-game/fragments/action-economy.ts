import type { ChapterUnitSummary } from "../../chapter-types";
import { driveUnitScene, type VerbCall } from "../../verb-runner";
import { buildBoundaryUnits, buildEconomyChannelUnits } from "../action-economy-units";
import { BUNDLE_ID } from "../constants";

export async function buildActionEconomyFragment(): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const boundaries = buildBoundaryUnits();
	const channels = buildEconomyChannelUnits();
	const calls: VerbCall[] = [
		{
			toolName: "spellkave_write_rows",
			label: "playing-the-game-boundaries",
			params: { bundle: BUNDLE_ID, kind: "boundary_definitions", rows: boundaries },
		},
		{
			toolName: "spellkave_write_rows",
			label: "playing-the-game-economy-channels",
			params: {
				bundle: BUNDLE_ID,
				kind: "economy_channel_definitions",
				rows: channels,
			},
		},
	];
	const body = await driveUnitScene(BUNDLE_ID, calls, undefined, {
		// These are the rows being authored by this fragment, not validation
		// fixtures. Avoid seeding the same rows into the throwaway workspace,
		// which would render each definition twice when retained below.
		retainActionEconomyDefinitions: true,
		seedActionEconomyDefinitions: false,
	});
	const units: ChapterUnitSummary[] = [
		...boundaries.map((row) => ({
			kind: "boundary_definitions",
			id: row.id,
			sourcePk: "",
		})),
		...channels.map((row) => ({
			kind: "economy_channel_definitions",
			id: row.id,
			sourcePk: "",
		})),
	];
	const header = [
		"# GENERATED by src/chapters/playing-the-game/fragments/action-economy.ts — DO NOT EDIT BY HAND.",
		"# Regenerate: pnpm --filter @spellkave/srd-cc run generate",
		"#",
		"# Complete, standalone SRD action economy: the srd bundle owns every",
		"# channel it consumes and carries no dependency-bundle references. Grounding:",
		"# playing-the-game.md §§ Actions, Combat, Time-Limited Object Interactions;",
		"# rules-glossary.md §§ Bonus Action, Reaction, Short Rest; ADR-0090 D-2.",
		"",
		"",
	].join("\n");
	return { toml: header + body, units };
}
