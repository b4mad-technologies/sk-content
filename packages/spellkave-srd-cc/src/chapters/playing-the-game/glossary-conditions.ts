/** Condition identities that ConditionDescription.json names and this chapter did not yet. */
import { readFileSync } from "node:fs";
import path from "node:path";
import type { AuthorTarget } from "@spellkave/tool-authoring";
import { CACHE_OPEN5E_DIR } from "../../open5e/paths.ts";
import type { ChapterUnitSummary } from "../chapter-types.ts";
import { driveUnitScene } from "../verb-runner.ts";

const MISSING = [
	"srd-2024_blinded",
	"srd-2024_deafened",
	"srd-2024_exhaustion",
	"srd-2024_petrified",
	"srd-2024_restrained",
	"srd-2024_stunned",
] as const;

export interface GlossaryConditionUnit {
	pk: string;
	slug: string;
	displayName: string;
	description: string;
}

function titleFromSlug(slug: string): string {
	return slug.slice(0, 1).toUpperCase() + slug.slice(1);
}

export function glossaryConditionUnits(): GlossaryConditionUnit[] {
	const raw: unknown = JSON.parse(
		readFileSync(path.join(CACHE_OPEN5E_DIR, "ConditionDescription.json"), "utf8"),
	);
	if (!Array.isArray(raw))
		throw new Error("glossary-conditions: ConditionDescription.json is not an array.");
	const byPk = new Map<string, { desc: string; describes: string }>();
	for (const row of raw) {
		const pk = (row as { pk?: unknown }).pk;
		const fields = (row as { fields?: { desc?: unknown; describes?: unknown } }).fields;
		if (
			typeof pk !== "string" ||
			typeof fields?.desc !== "string" ||
			typeof fields.describes !== "string"
		) {
			continue;
		}
		byPk.set(pk, { desc: fields.desc, describes: fields.describes });
	}
	return MISSING.map((pk) => {
		const row = byPk.get(pk);
		if (row === undefined) throw new Error(`glossary-conditions: missing ${pk}.`);
		const slug = pk.replace(/^srd-2024_/, "");
		return {
			pk,
			slug,
			displayName: titleFromSlug(row.describes),
			description: row.desc,
		};
	});
}

export async function buildGlossaryConditionsFragment(target?: AuthorTarget): Promise<{
	toml: string;
	units: ChapterUnitSummary[];
}> {
	const rows = glossaryConditionUnits();
	const body = await driveUnitScene(
		"srd",
		rows.map((row) => ({
			toolName: "spellkave_define_condition" as const,
			label: `condition:${row.slug}`,
			params: {
				bundle: "srd",
				id: `condition/${row.slug}`,
				display_name: row.displayName,
				description: row.description,
				observable: true,
				stacking_rule: "srd/stacking/single",
				remove_time_policy: "srd/remove_policy/independent_lifetime",
			},
		})),
		target,
	);
	return {
		toml:
			"# GENERATED by src/chapters/playing-the-game/glossary-conditions.ts — DO NOT EDIT BY HAND.\n" +
			"# Regenerate: pnpm --filter @spellkave/srd-cc run generate\n" +
			"# Identity only. No new disadvantage or save DSL.\n\n" +
			body,
		units: rows.map((row) => ({
			kind: "condition_definitions",
			id: `srd/condition/${row.slug}`,
			sourcePk: row.pk,
		})),
	};
}
